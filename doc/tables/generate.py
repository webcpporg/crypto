"""Writes crypto's generated tables, doc/generated/*.adoc, and its index for LLMs, doc/llms.txt.

Nothing in them is typed by hand. What crypto supports, on which backend and which target, comes
from the programs the test Jamfiles declare: an operation's backend is supported on the targets of
the tests doc/tables/crypto.json names for it, and refused where a message test of test/messages
stops it. The messages are the texts those tests and the MSVC cases fix, and the stops of the
superproject's fixtures of the user's Jamfiles (tools/test/fixtures/crypto_jamfiles/<case>/), whose
Jamfile lines and printed results the page shows as the fixtures hold them. crypto.json holds what
no build produces: the facts about the world with their sources, the use cases, the fix of each
message and the description of each fixture. A measurement no lane takes yet (size, throughput,
constant time measured) is written as not measured yet.

Each fact is checked against the tree: a test, a message case, a fixture or an example that
crypto.json names and the tree does not hold is a fault, and so is a fixture or a message case of
the tree that crypto.json does not describe.

Usage: generate.py [--check] [--root <superproject>]. Without --check it writes the files; with
it, it writes nothing and fails when a file differs from what it would write, which the doc
build runs (doc/Jamfile). Exit 0, 1 naming each fault, 2 on a usage error.
"""

