def constant_time_notes(data: Data) -> str:
    """What a family's backend measured on a target where it differs from the backend's design,
    crypto.json's per-target `constant_time` of a family, as a list after the table; nothing
    where no family states one."""
    notes: List[str] = []
    for family in data['families']:
        for backend, entry in family['backends'].items():
            for target, why in entry.get('constant_time', {}).items():
                notes.append(f"* {family['title']} on {data['backends'][backend]['title']}, "
                             f'{target}: {marked(cite(data, why))}')
    if not notes:
        return ''
    return ("\nMeasured where a family differs from its backend's design:\n\n"
            + '\n'.join(notes) + '\n')


def lane_cell(data: Data, backend: str, target: str) -> str:
    """The constant-time page's cell of a backend on a target: per checker of the lane, the
    families (and the backend's own `lane_paths`) it runs there, those with a measured finding
    marked; not measured yet where the lane runs none."""
    # Per checker, each family's title, its notes of that checker, and whether it measured
    # differently there; the backend's own paths have neither.
    by_checker: Dict[str, List[Tuple[str, List[str], bool]]] = {}
    for family in data.get('families', []):
        entry = family['backends'].get(backend, {})
        for checker in entry.get('lane', {}).get(target, []):
            note = entry.get('lane_note')
            notes = [marked(note)] if isinstance(note, str) else (
                [marked(note[checker])] if isinstance(note, dict) and checker in note else [])
            # A finding marks the checker that measured it, where crypto.json names one
            # (`constant_time_checker`), otherwise every checker of the target.
            found_by = entry.get('constant_time_checker', {}).get(target, checker)
            by_checker.setdefault(checker, []).append(
                (family['title'], notes,
                 target in entry.get('constant_time', {}) and found_by == checker))
    for path in data['backends'][backend].get('lane_paths', []):
        for checker in path['lane'].get(target, []):
            by_checker.setdefault(checker, []).append((marked(path['what']), [], False))
    if not by_checker:
        return NOT_MEASURED

    def listed(items: List[Tuple[str, List[str], bool]]) -> str:
        # A finding's note names its family where the checker lists several, so that it reads as
        # that family's alone, and not where the family is the only one.
        written: List[str] = []
        for title, notes, differs in items:
            if differs:
                notes = notes + ['measured differently, below' if len(items) == 1
                                 else f'{title} measured differently, below']
            written.append(title + (f' ({"; ".join(notes)})' if notes else ''))
        return ', '.join(written)

    return '; '.join(f'{title}: {listed(by_checker[name])}'
                     for name, title in data['checkers'].items() if name in by_checker)


def constant_time_page(data: Data) -> str:
    """Constant time per backend: by its library's design, and per target what the lane runs,
    from the same `lane` entries as the comparison tables."""
    rows: List[List[str]] = []
    for backend in libraries(data):
        facts = data['backends'][backend]
        sources = ''.join(f'; {{{source}}}' for source in facts['constant_time_sources'])
        rows.append([facts['title'], marked(cite(data, facts['constant_time'] + sources))]
                    + [lane_cell(data, backend, target) for target in data['targets']])
    return table(['Backend', 'By design'] + [f'Measured, {target}' for target in data['targets']],
                 rows) + constant_time_notes(data)


def digest_of(sizes: Data) -> str:
    """The SHA-256 of sizes without its digest, as generate.py --sizes writes it."""
    rest = {key: value for key, value in sizes.items() if key != 'digest'}
    return hashlib.sha256(json.dumps(rest, sort_keys=True).encode('utf-8')).hexdigest()


def imported(tables: List[Data]) -> Data:
    """doc/tables/sizes.json from the tables the lane sizes wrote (webcpp.program-sizes's
    <name>.sizes.json, one per table and target), each dated by its build: a table not built at
    variant=release, one of no program, and a program two tables measure on one target are
    refused."""
    seen: Dict[Tuple[str, str], int] = {}
    for index, sized in enumerate(tables):
        lacking = [key for key in TABLE_KEYS if key not in sized]
        if lacking:
            raise Fault(f'a table of the lane sizes lacks {", ".join(lacking)}: run the lane '
                        'again, whose tools/variants/variants.py writes them')
        variant = sized.get('variant')
        if variant != RELEASE:
            raise Fault(f'a size table is built only from release builds, not variant={variant}: '
                        'the lane sizes builds its tables at variant=release')
        if not sized.get('programs'):
            raise Fault(f'a table of the lane sizes on {sized.get("target")} holds no program')
        for row in sized['programs']:
            key = (row['program'], sized['target'])
            if seen.setdefault(key, index) != index and row['program'] != sized['baseline']:
                raise Fault(f'the lane\'s tables measure {key[0]} on {key[1]} twice')
    ordered = sorted(tables, key=lambda t: (t['target'], t['programs'][-1]['program']))
    out: Data = {'about': SIZES_ABOUT, 'tables': ordered}
    out['digest'] = digest_of(out)
    return out


def sized_on(sizes: Data, program: str, target: str) -> Optional[Tuple[int, int, int, int]]:
    """What program measured on target: its raw and gzip -9n bytes, and their excess over the
    baseline, summed over its files (on emscripten its .wasm and its .js); None where no table of
    target holds it."""
    rows = [row for sized in sizes['tables'] if sized['target'] == target
            for row in sized['programs'] if row['program'] == program]
    if not rows:
        return None
    files = {row['file']: row for row in rows}
    return (sum(row['bytes'] for row in files.values()),
            sum(row['gzip'] for row in files.values()),
            sum(row['over_baseline'] for row in files.values()),
            sum(row['gzip_over_baseline'] for row in files.values()))


def size_rows(data: Data) -> List[Tuple[str, Data, str, str]]:
    """The rows of the size matrix after the baseline's, in crypto.json's order: per cell of a
    family, (family, backend), the program <family>_<backend> of the family's fixed operation,
    `measured`, then one <family>_<backend>_<operation> per entry of its `sized_operations`.
    Each is (program, family, backend, the operation's text). A family without `measured` and two
    rows of one program name are faults."""
    rows: List[Tuple[str, Data, str, str]] = []
    for family in data['families']:
        if not isinstance(family.get('measured'), str):
            raise Fault(f'crypto.json: the family {family["name"]} has no measured, the text of '
                        'the fixed operation its sized programs call (test/sizes/Jamfile)')
        operations = family.get('sized_operations', {})
        if not isinstance(operations, dict) or not all(
                isinstance(text, str) for text in operations.values()):
            raise Fault(f'crypto.json: the family {family["name"]}\'s sized_operations is not an '
                        'object of operation names and their texts')
        for backend in family['backends']:
            cell = f'{family["name"]}_{backend}'
            rows.append((cell, family, backend, family['measured']))
            for operation, text in operations.items():
                rows.append((f'{cell}_{operation}', family, backend, text))
    names = [row[0] for row in rows]
    for name in names:
        if names.count(name) > 1 or name == 'baseline':
            raise Fault(f'crypto.json: two rows of the size matrix are the program {name}')
    return rows


def sizes_lead(data: Data, sizes: Data) -> str:
    """The sentence above the size matrix: when the lane measured it and, per target, with what
    and which file; natively the host and the executable's format."""
    dates = sorted({sized['date'] for sized in sizes['tables']})
    when = ' to '.join(dict.fromkeys([dates[0], dates[-1]])) if dates else 'no date yet'
    parts = []
    for target in data['targets']:
        found = [sized for sized in sizes['tables'] if sized['target'] == target]
        if not found:
            continue
        sized = found[0]
        if target == 'native':
            what = (f'on {sized["host"]}, the {sized["format"]} executable stripped, whose '
                    'segments are page-aligned: a small cell can add fewer raw bytes than its '
                    'code, which its gzip -9n bytes show better')
        elif target == 'emscripten':
            what = 'the .wasm and its .js'
        else:
            what = 'the .wasm'
        parts.append(f'{target}, {sized["toolset"]} {what}' if target == 'native'
                     else f'{target}, {sized["toolset"]}, {what}')
    return (f'The lane sizes measured on {when}, at variant=release: '
            f'{"; ".join(parts) or "no target yet"}.\n\n')


def sizes_page(data: Data, sizes: Data) -> str:
    """The size matrix: per row of size_rows, what its program of test/sizes adds to the
    baseline on each target, raw and gzip -9n, as the lane sizes measured it from release builds
    (doc/tables/sizes.json); not measured yet where the lane has not built it, and not on this
    target where the backend does not have the family there. Under it, the size note of each
    backend of a row (crypto.json's backends[].size_note)."""
    if sizes.get('digest') != digest_of(sizes):
        raise Fault(f'{SIZES} is not what generate.py --sizes wrote: write it again from the '
                    'lane sizes\' tables, never by hand')
    for sized in sizes['tables']:
        lacking = [key for key in TABLE_KEYS if key not in sized]
        if lacking:
            raise Fault(f'{SIZES} holds a table that lacks {", ".join(lacking)}: run the lane '
                        'sizes again and generate.py --sizes')
        if sized.get('variant') != RELEASE:
            raise Fault(f'a size table is built only from release builds, not '
                        f'variant={sized.get("variant")}')
    matrix = size_rows(data)
    known = {'baseline'} | {row[0] for row in matrix}
    for sized in sizes['tables']:
        for row in sized['programs']:
            if row['program'] not in known:
                raise Fault(f'{SIZES} measures {row["program"]}, which is no program the lane '
                            'sizes declares: its programs are baseline, <family>_<backend> for a '
                            'cell of crypto.json\'s families, and <family>_<backend>_<operation> '
                            'for an operation of the family\'s sized_operations')
    rows: List[List[str]] = []
    base = ['The baseline: the harness of every sized program, calling nothing of crypto']
    for target in data['targets']:
        measured = sized_on(sizes, 'baseline', target)
        base.append(f'{measured[0]:,} B, gzip {measured[1]:,} B' if measured else NOT_MEASURED)
    rows.append(base)
    noted: List[str] = []
    for program, family, backend, text in matrix:
        row = [f'{family["title"]} on {data["backends"][backend]["title"]}: {text}']
        have = cell_targets(data, family, backend)
        for target in data['targets']:
            measured = sized_on(sizes, program, target)
            if target not in have:
                row.append('not on this target')
            elif measured is None:
                row.append(NOT_MEASURED)
            else:
                row.append(f'+{measured[2]:,} B, gzip +{measured[3]:,} B')
        rows.append(row)
        if backend not in noted:
            noted.append(backend)
    notes = ''.join(f'\n{data["backends"][backend]["title"]}: '
                    f'{cite(data, data["backends"][backend]["size_note"])}\n'
                    for backend in backend_order(data) if backend in noted
                    and 'size_note' in data['backends'][backend])
    return (sizes_lead(data, sizes)
            + table(['Program'] + [f'Size, {target}' for target in data['targets']], rows,
                    'cols="3,2,2,2,2",') + notes)


def ed25519_cases_page(data: Data, cases: Data) -> str:
    """The twelve Ed25519 edge cases of meta/ed25519_cases.json: a row per case, what it tests,
    then each backend's raw verdict and its verdict under `strict`, then each outside view's,
    headed by the node and OpenSSL that gave it. A backend or an outside view the generator does
    not know, an outside view without its node and OpenSSL, a row whose length is not the cases'
    and a verdict other than accept or reject are faults."""
    columns = ['Case', 'What it tests']
    verdicts: List[List[str]] = []
    for backend in cases['backends']:
        if backend not in data['backends']:
            raise Fault(f'{ED25519_CASES} names the backend {backend}, which crypto.json does '
                        'not list')
    for backend in backend_order(data):
        rows = cases['backends'].get(backend)
        if rows is None:
            continue
        title = data['backends'][backend]['title']
        columns += [f'{title}, raw', f'{title}, strict']
        verdicts += [rows['raw'], rows['strict']]
    for name, view in cases['outside'].items():
        if name not in OUTSIDE_TITLES:
            raise Fault(f'{ED25519_CASES} names the outside view {name}, which generate.py does '
                        f'not know: {", ".join(OUTSIDE_TITLES)}')
        if not isinstance(view, dict) or not all(isinstance(view.get(key), str)
                                                 for key in ('node', 'openssl')):
            raise Fault(f'{ED25519_CASES}: the outside view {name} records no node and OpenSSL '
                        'versions')
        columns.append(OUTSIDE_TITLES[name].format(**view))
        verdicts.append(view.get('verdicts', []))
    for column, row in zip(columns[2:], verdicts):
        if len(row) != len(cases['cases']) or any(entry not in VERDICTS for entry in row):
            raise Fault(f'{ED25519_CASES}: the row {column} is not one verdict, accept or '
                        f'reject, per case: {row}')
    rows = [[str(index), marked(text)] + [row[index] for row in verdicts]
            for index, text in enumerate(cases['cases'])]
    widths = ','.join(['1', '5'] + ['2'] * len(verdicts))
    return table(columns, rows, f'cols="{widths}",')


def block(lines: List[str]) -> str:
    """A block of lines as they are, with no language: a Jamfile, which highlight.js does not
    know, or what a build prints."""
    return '[listing]\n----\n' + '\n'.join(lines) + '\n----'


def included(case: str, file: str, tag: str) -> str:
    """A block that includes a tagged region of a fixture's file, as the superproject tracks
    it."""
    return block([f'include::{{webcpp-root}}/{FIXTURES}/{case}/{file}[tag={tag}]'])


def printed(data: Data, outcome: Outcome) -> str:
    """What a failing fixture's build prints, as its outcome checks it: a list with an item per
    target and linker, which names it, and under it an item per text the output contains, as inline
    code, so that a long text breaks between its words as a sentence does rather than scroll."""
    labels: Dict[str, str] = data['outcome_sections']
    sections: List[str] = []
    for section, _ in outcome.contains:
        if section not in sections:
            sections.append(section)
    items: List[str] = []
    for section in sections:
        if section not in labels:
            raise Fault(f'a fixture\'s outcome has the section [{section}], which '
                        'crypto.json\'s outcome_sections does not name')
        texts = [code(text) for name, text in outcome.contains if name == section]
        label = labels[section]
        if section == 'all':
            label = ', '.join(outcome.targets) if outcome.targets else label
        items.append(f'* {label}:\n' + '\n'.join(f'** {text}' for text in texts))
    return '\n'.join(items)


def case_list(entries: List[Tuple[str, str, List[Tuple[str, str]]]]) -> str:
    """Cases as a list: each name with its description, then its blocks, each after the sentence
    that says what it is. A case's lines are as wide as its Jamfile and its build make them, so
    each block takes the page's width, rather than a column of a table that the widest line of
    any case would make wider than the page."""
    items: List[str] = []
    for term, description, blocks in entries:
        item = [f'{term}:: {description}']
        for caption, text in blocks:
            item += ['+', caption, '+', text]
        items.append('\n'.join(item))
    return '\n\n'.join(items) + '\n'


def jamfiles_page(data: Data, cases: Dict[str, Tuple[List[str], Outcome]]) -> str:
    """Every fixture that builds and runs: its Jamfile, its targets and what it prints."""
    entries: List[Tuple[str, str, List[Tuple[str, str]]]] = []
    for name, (_, outcome) in cases.items():
        if not outcome.succeeds or not outcome.runs:
            continue
        entries.append((code(name), marked(cite(data, data['fixtures'][name])), [
            (f'Its Jamfile, built and run on {", ".join(outcome.targets)}:',
             included(name, 'Jamfile', 'jamfile')),
            ('It prints:', included(name, f'{name}.outcome', 'output'))]))
    return case_list(entries)


def messages_page(data: Data, refusals: Dict[str, Tuple[str, List[str]]],
                  cases: Dict[str, Tuple[List[str], Outcome]], msvc: Dict[str, str]) -> str:
    """Every message: the compiler's, checked by a message test; the build's, from a fixture."""
    fixes: Dict[str, str] = data['fixes']
    rows: List[List[str]] = []
    for name, (text, targets) in refusals.items():
        if name not in fixes:
            raise Fault(f'the message test {name} has no fix in crypto.json')
        # The message as a sentence of code, which breaks between its words as the cell
        # does: one line of hundreds of characters would make the table scroll for all of it.
        # Its fix is the cell's second paragraph, so that the longest name of each does not
        # widen a column of its own.
        rows.append([code(name), ', '.join(targets),
                     f'{cell(code(text))}\n\nThe fix: {marked(fixes[name])}'])
    text = ('At compile time, checked word for word by the message tests of `test/messages` '
            'with clang:\n\n')
    text += table(['Case', 'Checked on', 'The message, and its fix'], rows, 'cols="2,1,7",')
    entries: List[Tuple[str, str, List[Tuple[str, str]]]] = []
    for name, (_, outcome) in cases.items():
        if outcome.succeeds:
            continue
        if name not in fixes:
            raise Fault(f'the fixture {name} has no fix in crypto.json')
        entries.append((code(name),
                        f'{marked(cite(data, data["fixtures"][name]))} '
                        f'The fix: {marked(fixes[name])}', [
                            ('Its Jamfile:', included(name, 'Jamfile', 'jamfile')),
                            ('On each target, the build\'s output contains:',
                             printed(data, outcome))]))
    text += ('\nAt build and link time, from the fixtures of the user\'s Jamfiles, each built on '
             'a scratch superproject: the texts the build\'s output contains, per target and '
             'linker, as each fixture checks them.\n\n')
    text += case_list(entries)
    windows: List[List[str]] = []
    for name, stage in msvc.items():
        fix = fixes.get(name) or fixes.get(f'{name}_msvc')
        if fix is None:
            raise Fault(f'the MSVC case {name} has no fix in crypto.json')
        windows.append([code(name), f'the {stage}', marked(fix)])
    text += ('\nOn MSVC, each case of `test/msvc` is proven to stop the build, at compile or '
             'at link time; its text is MSVC\'s own, the same instruction in MSVC\'s words, and '
             'two files compiled with different settings stop the link with LNK2038.\n\n')
    text += table(['Case', 'Stops', 'Fix'], windows, 'cols="1,1,4",')
    records = [(code(name), marked(cite(data, data['fixtures'][name])),
                [('Its Jamfile, which builds on ' + ', '.join(outcome.targets) + ':',
                  included(name, 'Jamfile', 'jamfile'))])
               for name, (_, outcome) in cases.items() if outcome.succeeds and not outcome.runs]
    if records:
        text += ('\nElsewhere than MSVC these mistakes build, and nothing stops them; the fixtures '
                 'record it:\n\n')
        text += case_list(records)
    return text


# The namespace every name of the decision table is in, which its cells leave out.
ROOT_NAMESPACE = 'webcpp::crypto'


def use_cases_page(data: Data, library: Path) -> str:
    """The decision table: what a program needs, and what to use. A name is written in the
    namespace under webcpp::crypto that holds it, so that no column is as wide as a namespace's
    full name."""
    rows: List[List[str]] = []
    ids = {operation['id'] for operation in data.get('operations', [])}
    for entry in data['use_cases']:
        unknown = [name for name in entry.get('operations', []) if name not in ids]
        if unknown:
            raise Fault(f'crypto.json: the use case "{entry["need"]}" names the operations '
                        f'{", ".join(unknown)}, which crypto.json does not describe')
        example = entry['example']
        if not example and entry['jamfile'] != 'none':
            raise Fault(f'crypto.json: the use case "{entry["need"]}" names no example: each '
                        'row a program can follow links one')
        if example and not (library / 'example' / f'{example}.cpp').is_file():
            raise Fault(f'crypto.json: the use case "{entry["need"]}" names the example '
                        f'{example}, which example/ does not hold')
        shown = (f'<<{entry["section"]},{kept(f"{example}.cpp")}>>' if example
                 else f'<<{entry["section"]}>>')
        namespace = entry['namespace']
        if namespace == ROOT_NAMESPACE:
            use = marked(entry['api'])
        elif namespace.startswith(f'{ROOT_NAMESPACE}::'):
            use = f'In {code(namespace[len(ROOT_NAMESPACE) + 2:])}: {marked(entry["api"])}'
        else:
            use = f'{namespace[:1].upper()}{namespace[1:]}: {marked(entry["api"])}'
        # Each target on a line of its own, a path that breaks after a / where the table does
        # not fit otherwise.
        if '`' in entry['jamfile']:
            jamfile = TICKED.sub(lambda match: code(match.group(1)), entry['jamfile'])
        elif entry['jamfile'] == 'none':
            jamfile = 'none'
        else:
            jamfile = ' +\n'.join(code(target) for target in entry['jamfile'].split())
        rows.append([entry['need'], use, entry['backend'], jamfile, shown])
    # key-column: the column a reader starts from, "I need to", keeps room for a few words a
    # line; where the table does not fit with its names whole, the names of "Use" break after
    # their :: and the targets after a /, and where it does not fit even so it stacks, its names
    # never broken at a _; examples' files stay whole, as a reader copies them
    # (tools/doc/docinfo.html).
    return table(['I need to', 'Use', 'Backend', 'Jamfile', 'Example'], rows,
                 '.key-column,cols="3,3,2,3,2",')


HEADER = re.compile(r'<(webcpp/crypto/[\w/]+\.hpp)>')
# A reference to a line of a header, "(`include/secp256k1.h:235-247`)": the headers' own
# business, and stale once the line moves, so llms.txt leaves it out.
LINE_REFERENCE = re.compile(r'\s*\(`[\w./-]+:\d+(?:-\d+)?`\)')
DOC_COMMENT = re.compile(r'/\*\*(.*?)\*/', re.S)


def class_body(text: str, name: str) -> str:
    """The body of the class or struct name that text defines, between its braces, or nothing
    when text defines none of that name."""
    found = re.search(rf'\b(?:class|struct)\s+{re.escape(name)}\b[^;{{]*\{{', text)
    if not found:
        return ''
    depth = 0
    for index in range(found.end() - 1, len(text)):
        depth += {'{': 1, '}': -1}.get(text[index], 0)
        if depth == 0:
            return text[found.end():index]
    return text[found.end():]


def declared_brief(library: Path, operation: Data, function: str) -> str:
    """The first sentence of the Doc Comment of a function an operation names, read from the
    operation's headers: the description llms.txt gives it. A function written `class::name` is
    read in that class's body alone, for a name that another class of the header declares first.
    A function the operation's `overloads` name is read in the first declaration that holds the
    text they give it, for a name another family's overload declares first. A function no header
    declares is a fault."""
    scope, _, name = function.rpartition('::')
    overload = operation.get('overloads', {}).get(function)
    if name == 'operator()':
        pattern = re.compile(r'\boperator\(\)\(')
    else:
        pattern = re.compile(rf'(?:\b{re.escape(name)}|\({re.escape(name)}\))\s*\(')
    for header in HEADER.findall(operation['header']):
        text = (library / 'include' / header).read_text(encoding='utf-8')
        if scope:
            text = class_body(text, scope)
        for comment in DOC_COMMENT.finditer(text):
            rest = text[comment.end():]
            declaration = rest[:rest.find('{') if '{' in rest else len(rest)]
            declaration = declaration.split(';', 1)[0]
            declaration = '\n'.join(line.split('//', 1)[0] for line in declaration.splitlines())
            free = not declaration.lstrip('\n').startswith(' ')
            if operation.get('free') and not free and not scope:
                continue
            if overload is not None and overload not in declaration:
                continue
            found = pattern.search(declaration)
            # The declared name: the first parenthesis of the declaration is its own.
            if found and '(' not in declaration[:found.start()] and '/*' not in declaration:
                words = ' '.join(line.strip().lstrip('*').strip()
                                 for line in comment.group(1).splitlines()).strip()
                words = LINE_REFERENCE.sub('', words.replace('@ref ', ''))
                return re.split(r'(?<=\.)\s', words, maxsplit=1)[0]
    held = f' with {overload} in its declaration' if overload is not None else ''
    raise Fault(f'crypto.json names {function} of {operation["id"]}, which no Doc Comment of '
                f'{operation["header"]} declares{held}')


def llms_entry(library: Path, operation: Data, function: str) -> str:
    """The line of llms.txt that lists a function of an operation, under the operation's entry:
    its bare name, a function written `class::name` included, and its brief."""
    name = function.rpartition('::')[2]
    return f'  - {name}: {declared_brief(library, operation, function)}'


def first_comment(source: Path) -> str:
    """The comment that opens an example after its licence: what the program does."""
    lines = source.read_text(encoding='utf-8').splitlines()[6:]
    words: List[str] = []
    for line in lines:
        if not line.startswith('//') or line.startswith('// tag::'):
            break
        words.append(line[2:].strip())
    return ' '.join(words)


def llms_default(data: Data, operation: Data) -> str:
    """An operation's default backend per target in llms.txt, from its own family's row ("none"
    where the family has none)."""
    name = operation.get('family')
    if name is None:
        return ''
    defaults = [f'{default_title(data, entry)} on {target_label(data, entry)}'
                for entry in family_of(data, name)['default']]
    if not defaults:
        return ''
    return f' Default: {"; ".join(defaults)}.'


def llms_uses(data: Data, operation: Data) -> str:
    """The use cases of the decision table that an operation answers: of its section, or whose
    `answers` names it where the use case links a teaching chapter instead, naming one of its
    names; a use case that lists its `operations` answers those alone."""
    named = [part.rpartition('::')[2] for part in operation['api'].split(', ')]
    needs = [entry['need'][:1].lower() + entry['need'][1:] for entry in data['use_cases']
             if entry.get('answers', entry['section']) == operation['section']
             and operation.get('id') in entry.get('operations', [operation.get('id')])
             and any(re.search(rf'\b{re.escape(name)}\b', entry['api']) for name in named)]
    return f' Use it to: {"; ".join(needs)}.' if needs else ''


def llms(data: Data, matrix: Matrix, library: Path) -> str:
    """The index for LLMs, in the llms.txt form: what crypto offers, where, and for what."""
    page = data['page']
    out = ['# webcpp::crypto', '', f'> {data["llms"]}', '',
           f'Generated by doc/tables/generate.py with the page\'s tables. Page: {page}', '']
    for namespace, title in namespace_titles(data).items():
        out += [f'## {title}', '']
        for operation in data['operations']:
            if operation['namespace'] != namespace:
                continue
            backends = '; '.join(
                f'{data["backends"][backend]["title"]} ({data["backends"][backend]["jamfile"]}) '
                f'on {", ".join(matrix.supported[(operation["id"], backend)])}'
                for backend in matrix.backends_of(operation['id'])
                if (operation['id'], backend) in matrix.supported)
            out.append(f'- [{operation["api"]}]({page}#{operation["section"]}): '
                       f'{operation["what"]} Header {operation["header"]}. Backends: {backends}.'
                       + llms_default(data, operation) + llms_uses(data, operation))
            out += [llms_entry(library, operation, function)
                    for function in operation['functions']]
        out.append('')
    out += ['## Default backend per family', '']
    for family in data['families']:
        for entry in family['default']:
            out.append(f'- {family["title"]}, {target_label(data, entry)}: '
                       f'{default_title(data, entry)}; {cite_markdown(data, entry["why"])}.')
    out += ['', '## Constant time, measured', '']
    out += [f'- {family["title"]}: {lane_text(data, family, cite_markdown, str)}.'
            for family in data['families']]
    out += ['', '## Rules of use', '']
    for rule in data['rules']:
        out.append(f'- [{rule["title"]}]({page}#{rule["section"]}): '
                   f'{cite_markdown(data, rule["text"])}')
    out += ['', '## Choose by use case', '']
    for entry in data['use_cases']:
        example = f' Example: example/{entry["example"]}.cpp.' if entry['example'] else ''
        out.append(f'- [{entry["need"]}]({page}#{entry["section"]}): {entry["api"]} '
                   f'({entry["namespace"]}); backend {entry["backend"]}; Jamfile '
                   f'{entry["jamfile"]}.{example}')
    out += ['', '## Examples', '']
    for source in sorted((library / 'example').glob('*.cpp')):
        out.append(f'- example/{source.name}: {first_comment(source)}')
    out += ['', '## Optional', '',
            f'- [Every message and its fix]({page}#crypto-jamfile-messages)',
            f'- [The backends]({page}#crypto-backends)',
            f'- [Reference]({page}#reference)', '']
    return '\n'.join(out)


def read_performance(library: Path) -> Data:
    """doc/performance.json, which bench/collect.py writes from release builds, or no
    measurement before it has run."""
    path = library / PERFORMANCE
    if not path.is_file():
        return {'cases': []}
    performance: Data = json.loads(path.read_text(encoding='utf-8'))
    if performance.get('build') != f'variant={RELEASE}':
        raise Fault(f'{PERFORMANCE} was built at {performance.get("build", "no variant")}, not '
                    f'variant={RELEASE}: measure again with bench/collect.py')
    return performance


def read_sizes(library: Path) -> Data:
    """doc/tables/sizes.json, or, before the lane has been read, sizes of no table."""
    path = library / SIZES
    if not path.is_file():
        return imported([])
    return json.loads(path.read_text(encoding='utf-8'))


def write_sizes(library: Path, files: List[Path]) -> None:
    """--sizes: writes doc/tables/sizes.json from the lane's <name>.sizes.json files."""
    tables = [json.loads(path.read_text(encoding='utf-8')) for path in files]
    sizes = imported(tables)
    (library / SIZES).write_text(json.dumps(sizes, indent=2) + '\n', encoding='utf-8')


def generate(root: Path, library: Path) -> Dict[Path, str]:
    """Every generated file, by its path, with its content."""
    data: Data = json.loads((HERE / 'crypto.json').read_text(encoding='utf-8'))
    declared = tests(library)
    refusals = messages(library)
    cases = fixtures(root)
    for name in cases:
        if name not in data['fixtures']:
            raise Fault(f'the fixture {name} names crypto and crypto.json does not describe it')
    for name in data['fixtures']:
        if name not in cases:
            raise Fault(f'crypto.json describes the fixture {name}, which the tree does not hold')
    matrix = Matrix(data, declared, refusals)
    check_families(data, declared)
    generated = DOC / 'generated'
    files: Dict[Path, str] = {}
    performance = read_performance(library)
    for namespace in namespace_titles(data):
        files[generated / f'namespace-{namespace}.adoc'] = namespace_page(data, namespace,
                                                                          performance)
    for operation in data['operations']:
        files[generated / f'backends-{operation["id"]}.adoc'] = api_backends(data, matrix,
                                                                             operation)
    files[generated / 'matrix.adoc'] = matrix_page(data, matrix)
    files[generated / 'backend-facts.adoc'] = facts_page(data, matrix)
    files[generated / 'defaults.adoc'] = defaults_page(data)
    files[generated / 'constant-time.adoc'] = constant_time_page(data)
    files[generated / 'sizes.adoc'] = sizes_page(data, read_sizes(library))
    files[generated / 'jamfiles.adoc'] = jamfiles_page(data, cases)
    files[generated / 'default-aliases.adoc'] = aliases_page(data, cases)
    files[generated / 'messages.adoc'] = messages_page(data, refusals, cases,
                                                       msvc_cases(library))
    files[generated / 'use-cases.adoc'] = use_cases_page(data, library)
    files[library / CAPABILITIES] = capabilities_header(data)
    files[library / CAPABILITIES_TEST] = capabilities_test(data)
    files[library / DEFAULTS] = defaults_header(data)
    for path in list(files):
        files[path] = NOTICE + files[path]
    cases_data: Data = json.loads((library / ED25519_CASES).read_text(encoding='utf-8'))
    files[generated / 'ed25519-cases.adoc'] = CASES_NOTICE + ed25519_cases_page(data, cases_data)
    files[DOC / 'llms.txt'] = llms(data, matrix, library)
    files[library / BUILD] = with_aliases((library / BUILD).read_text(encoding='utf-8'),
                                          default_aliases(data))
    return files


def checked(files: Dict[Path, str], library: Path, generated: Path) -> int:
    """--check: prints each file that differs from what generate.py writes, and each page of
    generated that it does not write, by its path in library. 1 when there is one, else 0."""
    differing = stale(files)
    extra = sorted(path for path in generated.glob('*.adoc') if path not in files)
    for path in differing:
        print(f'generate.py: {path.relative_to(library)} is not what crypto.json and the tree '
              'give: run python3 libs/crypto/doc/tables/generate.py', file=sys.stderr)
    for path in extra:
        print(f'generate.py: {path.relative_to(library)} is generated by nothing: remove it',
              file=sys.stderr)
    return 1 if differing or extra else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or '').split('\n', 1)[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=LIBRARY.parent.parent)
    parser.add_argument('--sizes', type=Path, nargs='+', metavar='JSON',
                        help='the tables the lane sizes wrote, <name>.sizes.json, which it '
                        'writes into doc/tables/sizes.json before the pages')
    arguments = parser.parse_args()
    if arguments.check and arguments.sizes:
        parser.error('--check writes nothing, and --sizes writes doc/tables/sizes.json')
    try:
        if arguments.sizes:
            write_sizes(LIBRARY, arguments.sizes)
        files = generate(arguments.root.resolve(), LIBRARY)
    except Fault as fault:
        print(f'generate.py: {fault}', file=sys.stderr)
        return 1
    if arguments.check:
        return checked(files, LIBRARY, DOC / 'generated')
    differing = stale(files)
    extra = sorted(path for path in (DOC / 'generated').glob('*.adoc') if path not in files)
    for path in differing:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding='utf-8')
    for path in extra:
        path.unlink()
    return 0


if __name__ == '__main__':
    sys.exit(main())
