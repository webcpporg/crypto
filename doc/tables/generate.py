"""Writes crypto's generated tables, doc/generated/*.adoc, its index for LLMs, doc/llms.txt, and
the capability table's C++: include/webcpp/crypto/detail/capabilities.hpp and its test,
test/capabilities_test.cpp.

Nothing in them is typed by hand. What crypto supports, on which backend and which target, comes
from the programs the test Jamfiles declare: an operation's backend is supported on the targets of
the tests doc/tables/crypto.json names for it, and refused where a message test of test/messages
stops it. The messages are the texts those tests and the MSVC cases fix, and the stops of the
superproject's fixtures of the user's Jamfiles (tools/test/fixtures/crypto_jamfiles/<case>/), whose
Jamfile lines and printed results the page shows as the fixtures hold them. crypto.json holds what
no build produces: the facts about the world with their sources, the use cases, the fix of each
message and the description of each fixture. The table of Ed25519's twelve edge cases is
meta/ed25519_cases.json's, the verdicts test/ed25519_speccheck_test.cpp asserts. A measurement no
lane takes yet is written as not measured yet.

Each namespace's comparison table is crypto.json's rows, with two kinds of cell written from the
data: {speed:<family>}, the family's throughput from doc/performance.json (bench/collect.py, release
builds only), and {constant_time:<family>}, what crypto.json records of the family's measured
constant time; a fact about the world in a column the namespace lists as `cited` holds a source or
begins with "none", or the table is refused naming its row. The namespaces and the backends are
crypto.json's, in its order; llms.txt's summary is its `llms`, and each operation's entry gives its
backends, its default per target and the use cases that name it (a use case's `operations`, when
it has them, limit it to those operations' ids, for a name that several families' operations
share). A function's brief is its Doc Comment's first sentence; an operation's `overloads` name,
per function, a text its declaration holds, for a name another family's overload declares first.

The capability table is crypto.json's families: each family's algorithms and, per backend, the
targets on which it has them, which the tests of the family's operations must run on (a cell is
claimed only where a named test runs), and its default per target with the reason. From it come
the family and algorithm tags, `detail::supported`, which `supports_v` reads, the refusal of a
backend without the family, which names the backends that have it, and the test that asserts each
cell and makes each present one.

Each fact is checked against the tree: a test, a message case, a fixture or an example that
crypto.json names and the tree does not hold is a fault, and so is a fixture or a message case of
the tree that crypto.json does not describe.

The size matrix is the own lane sizes' (test/sizes/Jamfile): `--sizes <json>...` reads the tables
the lane wrote at variant=release on each target (webcpp.program-sizes's <name>.sizes.json), and
writes them, dated, into doc/tables/sizes.json, which no hand edits (its digest is checked); a cell
the lane has not built is not measured yet.

Usage: generate.py [--check] [--root <superproject>] [--sizes <json>...]. Without --check it writes
the files; with it, it writes nothing and fails when a file differs from what it would write, which
the doc build runs (doc/Jamfile). Exit 0, 1 naming each fault, 2 on a usage error.
"""

