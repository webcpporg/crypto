FIXTURES = 'tools/test/fixtures/crypto_jamfiles'
BACKEND_ORDER = ('bearssl', 'openssl', 'ctaes', 'secp256k1', 'system', 'none')
NAMESPACE_TITLES = {'root': 'webcpp::crypto', 'ciphers': 'webcpp::crypto::ciphers',
                    'curves': 'webcpp::crypto::curves'}
RUN_RULES = ('crypto-run', 'webcpp.run', 'webcpp.compile', 'webcpp.compile-diagnostic',
             'webcpp.compile-fail', 'webcpp.link-fail', 'webcpp.example')
EXPECTED_ERROR = re.compile(r'expected-error@\S+ \{\{(.*)\}\}')
SOURCE = re.compile(r'\{([a-z0-9-]+)\}')
NOT_MEASURED = 'not measured yet'

Data = Dict[str, Any]


class Fault(Exception):
    """A fact of crypto.json that the tree does not hold, or the reverse."""


def statements(jamfile: Path) -> List[List[List[str]]]:
    """Each statement of a Jamfile at its top level, its words cut into fields at each `:`.

    The body of a rule is skipped: it declares nothing until the rule is called. A program
    declared inside another block, an `if` or a `for`, is a fault: its targets would depend on
    a condition this reading does not evaluate, and the tables would say it runs everywhere.
    """
    words: List[str] = []
    for line in jamfile.read_text(encoding='utf-8').splitlines():
        words += line.split('#', 1)[0].split()
    found: List[List[List[str]]] = []
    current: List[List[str]] = [[]]
    blocks: List[str] = []
    for word in words:
        if word == '{':
            blocks.append('rule' if current[0][:1] == ['rule'] else 'other')
            current = [[]]
        elif word == '}':
            if blocks:
                blocks.pop()
            current = [[]]
        elif word == ';':
            head = current[0]
            if head and head[0] in RUN_RULES and 'other' in blocks and 'rule' not in blocks:
                raise Fault(f'{jamfile}: {head[0]} {head[1:2]} is declared inside a block, '
                            'which generate.py does not evaluate')
            if current != [[]] and not blocks:
                found.append(current)
            current = [[]]
        elif word == ':':
            current.append([])
        else:
            current[-1].append(word)
    return found


def programs(jamfile: Path, inherited: Optional[List[str]] = None) -> Dict[str, List[str]]:
    """The targets of each program a Jamfile declares with webcpp's rules, by its name."""
    default = list(inherited or ['native'])
    found: Dict[str, List[str]] = {}
    for fields in statements(jamfile):
        head = fields[0]
        if head and head[0] == 'webcpp.targets':
            default = head[1:]
        elif head and head[0] in RUN_RULES and len(head) > 1:
            targets = fields[3] if len(fields) > 3 and fields[3] else default
            found[head[1]] = list(targets)
    return found


def tests(library: Path) -> Dict[str, List[str]]:
    """Every program of the test Jamfile and of each message test, with its targets."""
    found = programs(library / 'test' / 'Jamfile')
    for jamfile in sorted((library / 'test' / 'messages').glob('*/Jamfile')):
        found.update(programs(jamfile))
    return found


def messages(library: Path) -> Dict[str, Tuple[str, List[str]]]:
    """Each message test's case: the text its source states, and its targets."""
    found: Dict[str, Tuple[str, List[str]]] = {}
    for directory in sorted((library / 'test' / 'messages').iterdir()):
        if not directory.is_dir():
            continue
        declared = programs(directory / 'Jamfile')
        for source in sorted(directory.glob('*.cpp')):
            for line in source.read_text(encoding='utf-8').splitlines():
                text = EXPECTED_ERROR.search(line)
                if text and source.stem in declared:
                    found[source.stem] = (text.group(1), declared[source.stem])
    return found


def msvc_cases(library: Path) -> Dict[str, str]:
    """Each MSVC case, and whether it stops at compile or at link time."""
    found: Dict[str, str] = {}
    for jamfile in sorted((library / 'test' / 'msvc').glob('*/Jamfile')):
        for fields in statements(jamfile):
            head = fields[0]
            if head and head[0] in ('webcpp.compile-fail', 'webcpp.link-fail'):
                found[head[1]] = 'compile' if head[0] == 'webcpp.compile-fail' else 'link'
    return found


class Outcome:
    """A fixture's .outcome: its targets, whether it builds, what it prints or contains."""

    def __init__(self, path: Path) -> None:
        self.targets: List[str] = []
        self.succeeds = False
        self.output: List[str] = []
        self.contains: List[Tuple[str, str]] = []
        section = 'all'
        printing = False
        for line in path.read_text(encoding='utf-8').splitlines():
            if not line or line.startswith('#'):
                continue
            if line.startswith('[') and line.endswith(']'):
                section = line[1:-1]
                printing = False
            elif line.startswith('targets:'):
                self.targets = line.split()[1:]
            elif line.startswith('build:'):
                self.succeeds = line.split()[1] == 'succeeds'
            elif line.startswith('run:'):
                printing = True
            elif line.startswith('contains:'):
                self.contains.append((section, line[len('contains:'):].strip()))
            elif printing:
                self.output.append(line)


def fixtures(root: Path) -> Dict[str, Tuple[List[str], Outcome]]:
    """Each fixture of the user's Jamfiles that names crypto: its Jamfile's lines, its outcome."""
    found: Dict[str, Tuple[List[str], Outcome]] = {}
    directory = root / FIXTURES
    for case in sorted(path for path in directory.iterdir() if path.is_dir()):
        jamfile = case / 'Jamfile'
        lines = [line for line in jamfile.read_text(encoding='utf-8').splitlines()
                 if line.strip() and not line.startswith('#')]
        if not any('/webcpp/crypto//crypto' in line for line in lines):
            continue
        outcome = Outcome(case / f'{case.name}.outcome')
        tag = 'output' if outcome.succeeds else 'messages'
        for file, wanted in (('Jamfile', 'jamfile'), (f'{case.name}.outcome', tag)):
            text = (case / file).read_text(encoding='utf-8')
            if f'tag::{wanted}[]' not in text or f'end::{wanted}[]' not in text:
                raise Fault(f'the fixture {case.name}: {file} has no region {wanted}, which '
                            'the page includes')
        found[case.name] = (lines, outcome)
    return found


def cite(data: Data, text: str) -> str:
    """text with each {source} written as a link to the source crypto.json names."""
    def link(match: 're.Match[str]') -> str:
        source = data['sources'].get(match.group(1))
        if source is None:
            raise Fault(f'crypto.json names the source {match.group(1)}, which it does not list')
        return f'link:{source[1]}[{source[0]}]'
    return SOURCE.sub(link, text)


def cell(text: str) -> str:
    """text made safe in a cell of a table: no | read as the cell's end."""
    return text.replace('|', '\\|')


def code(text: str) -> str:
    """text as inline code, every character as it is."""
    return f'`+{text}+`'


def table(columns: List[str], rows: List[List[str]], style: str = '') -> str:
    """An AsciiDoc table with a header row."""
    head = f'[{style}options="header"]\n' if style else '[options="header"]\n'
    lines = [head + '|===']
    lines.append(' '.join(f'|{cell(column)}' for column in columns))
    for row in rows:
        lines.append('')
        lines.extend(value if value.startswith('a|') else f'|{value}' for value in row)
    lines.append('|===')
    return '\n'.join(lines) + '\n'


class Matrix:
    """The support of each operation on each backend and target, from the tests' targets."""

    def __init__(self, data: Data, declared: Dict[str, List[str]],
                 refusals: Dict[str, Tuple[str, List[str]]]) -> None:
        self.data = data
        self.supported: Dict[Tuple[str, str], List[str]] = {}
        self.proofs: Dict[Tuple[str, str], List[str]] = {}
        self.refused: Dict[Tuple[str, str], str] = {}
        for operation in data['operations']:
            for backend, entry in operation['backends'].items():
                key = (operation['id'], backend)
                if 'tests' in entry:
                    targets: List[str] = []
                    for name in entry['tests']:
                        if name not in declared:
                            raise Fault(f'crypto.json: {operation["id"]} on {backend} names the '
                                        f'test {name}, which no test Jamfile declares')
                        targets += declared[name]
                    self.supported[key] = [target for target in data['targets']
                                           if target in targets]
                    self.proofs[key] = list(entry['tests'])
                else:
                    if entry['refused'] not in refusals:
                        raise Fault(f'crypto.json: {operation["id"]} on {backend} is refused by '
                                    f'{entry["refused"]}, which no message test declares')
                    self.refused[key] = entry['refused']

    def backends_of(self, operation: str) -> List[str]:
        """The backends that implement or refuse an operation, in the page's order."""
        return [backend for backend in BACKEND_ORDER
                if (operation, backend) in self.supported or (operation, backend) in self.refused]

    def targets_of(self, backend: str) -> List[str]:
        """Every target on which a backend implements something."""
        found = {target for (_, name), targets in self.supported.items() if name == backend
                 for target in targets}
        return [target for target in self.data['targets'] if target in found]

    def describe(self, operation: str, backend: str) -> str:
        """A cell: the targets an operation runs on with a backend, or why it does not."""
        key = (operation, backend)
        if key in self.supported:
            targets = ', '.join(self.supported[key])
            missing = [target for target in self.data['targets']
                       if target not in self.supported[key]]
            proven = ', '.join(code(name) for name in self.proofs[key])
            text = f'{targets} (tested by {proven})'
            if missing and backend == 'openssl':
                text += f'; not on {", ".join(missing)}: {self.data["elsewhere"]["openssl"]}'
            return text
        if key in self.refused:
            return f'{self.data["elsewhere"]["refused"]} ({code(self.refused[key])})'
        return 'no'


def namespace_page(data: Data, namespace: str) -> str:
    """A namespace's comparison table."""
    entry = data['namespaces'][namespace]
    rows = [[cite(data, value) for value in row] for row in entry['rows']]
    return table(entry['columns'], rows)


def api_backends(data: Data, matrix: Matrix, operation: Data) -> str:
    """The backends that implement an operation, with their targets and Jamfile lines."""
    rows: List[List[str]] = []
    for backend in matrix.backends_of(operation['id']):
        facts = data['backends'][backend]
        rows.append([facts['title'], code(facts['jamfile']), code(facts['header']),
                     matrix.describe(operation['id'], backend)])
    return (f'The backends of {code(operation["api"])}, from the test programs that run it:\n\n'
            + table(['Backend', 'Jamfile', 'Header', 'Targets'], rows, 'cols="1,2,2,4",'))


def matrix_page(data: Data, matrix: Matrix) -> str:
    """Operations x backends, then operations x targets."""
    backends = list(BACKEND_ORDER)
    rows = [[code(operation['api'])] + [matrix.describe(operation['id'], backend)
                                         for backend in backends]
            for operation in data['operations']]
    text = table(['Operation'] + [data['backends'][backend]['title'] for backend in backends],
                 rows)
    by_target: List[List[str]] = []
    for operation in data['operations']:
        row = [code(operation['api'])]
        for target in data['targets']:
            names = [data['backends'][backend]['title'] for backend in backends
                     if target in matrix.supported.get((operation['id'], backend), [])]
            row.append(', '.join(names) if names else 'none')
        by_target.append(row)
    text += '\nThe same, by target: the backends each operation runs on.\n\n'
    text += table(['Operation'] + data['targets'], by_target)
    return text


def facts_page(data: Data, matrix: Matrix) -> str:
    """Each backend: its Jamfile line, header, library, licence, own API, allocation, targets."""
    rows: List[List[str]] = []
    for backend in BACKEND_ORDER[:4]:
        facts = data['backends'][backend]
        rows.append([facts['title'], code(facts['jamfile']), code(facts['header']),
                     facts['library'], facts['licence'], code(facts['own_api']),
                     facts['allocation'], ', '.join(matrix.targets_of(backend))])
    return table(['Backend', 'Jamfile', 'Header', 'Library', 'Licence', 'Its own API, reachable',
                  'Allocation', 'Targets'], rows)


def defaults_page(data: Data, declared: Dict[str, List[str]]) -> str:
    """The default backend per target and what is linked, each with the tests that fix it."""
    rows: List[List[str]] = []
    for entry in data['defaults']:
        for name in entry['tests']:
            if name not in declared:
                raise Fault(f'crypto.json: the default on {entry["target"]} names the test '
                            f'{name}, which no test Jamfile declares')
        rows.append([entry['target'], entry['linked'],
                     data['backends'][entry['default']]['title'], cite(data, entry['why']),
                     ', '.join(code(name) for name in entry['tests'])])
    return table(['Target', 'Linked', 'Default', 'Why', 'Tested by'], rows)


def constant_time_page(data: Data) -> str:
    """Constant time per backend: by its library's design, and measured per target."""
    rows: List[List[str]] = []
    for backend in BACKEND_ORDER[:4]:
        facts = data['backends'][backend]
        sources = ''.join(f'; {{{source}}}' for source in facts['constant_time_sources'])
        rows.append([facts['title'], cite(data, facts['constant_time'] + sources)]
                    + [NOT_MEASURED for _ in data['targets']])
    return table(['Backend', 'By design'] + [f'Measured, {target}' for target in data['targets']],
                 rows)


def sizes_page(data: Data) -> str:
    """Size per target and throughput per operation: no lane measures them yet."""
    rows = [[code(operation['api'])] + [NOT_MEASURED for _ in data['targets']]
            + [NOT_MEASURED, NOT_MEASURED]
            for operation in data['operations'] if operation['namespace'] != 'root']
    return table(['Operation'] + [f'Size, {target}' for target in data['targets']]
                 + ['Throughput, native', 'Throughput, node'], rows)


def listing(lines: List[str], language: str = '') -> str:
    """A cell holding a block of lines as they are."""
    style = f'[source,{language}]\n' if language else '[listing]\n'
    # The block's attribute list on a line of its own, after a blank line, as Asciidoctor and
    # doc-check read a block that opens a cell.
    return 'a|\n\n' + style + '----\n' + '\n'.join(lines) + '\n----'


def included(case: str, file: str, tag: str, language: str = '') -> str:
    """A cell that includes a tagged region of a fixture's file, as the superproject tracks it."""
    return listing([f'include::{{webcpp-root}}/{FIXTURES}/{case}/{file}[tag={tag}]'], language)


def jamfiles_page(data: Data, cases: Dict[str, Tuple[List[str], Outcome]]) -> str:
    """Every fixture that builds: its Jamfile, its targets and what it prints."""
    rows: List[List[str]] = []
    for name, (_, outcome) in cases.items():
        if not outcome.succeeds:
            continue
        rows.append([f'{code(name)}: {data["fixtures"][name]}',
                     included(name, 'Jamfile', 'jamfile', 'bash'),
                     ', '.join(outcome.targets), included(name, f'{name}.outcome', 'output')])
    return table(['Case', 'Jamfile', 'Built and run on', 'It prints'], rows, 'cols="2,4,1,2",')


def messages_page(data: Data, refusals: Dict[str, Tuple[str, List[str]]],
                  cases: Dict[str, Tuple[List[str], Outcome]], msvc: Dict[str, str]) -> str:
    """Every message: the compiler's, checked by a message test; the build's, from a fixture."""
    fixes: Dict[str, str] = data['fixes']
    rows: List[List[str]] = []
    for name, (text, targets) in refusals.items():
        if name not in fixes:
            raise Fault(f'the message test {name} has no fix in crypto.json')
        rows.append([code(name), ', '.join(targets), listing([text]), fixes[name]])
    text = ('At compile time, checked word for word by the message tests of `test/messages` '
            'with clang:\n\n')
    text += table(['Case', 'Checked on', 'Message', 'Fix'], rows, 'cols="1,1,5,2",')
    build: List[List[str]] = []
    for name, (_, outcome) in cases.items():
        if outcome.succeeds:
            continue
        if name not in fixes:
            raise Fault(f'the fixture {name} has no fix in crypto.json')
        build.append([f'{code(name)}: {data["fixtures"][name]}',
                      included(name, 'Jamfile', 'jamfile', 'bash'),
                      included(name, f'{name}.outcome', 'messages'), fixes[name]])
    text += ('\nAt build and link time, from the fixtures of the user\'s Jamfiles, each built on '
             'a scratch superproject: what the build prints, per target and linker, as each '
             'fixture checks it.\n\n')
    text += table(['Case', 'Jamfile', 'The build prints', 'Fix'], build, 'cols="2,3,4,2",')
    windows: List[List[str]] = []
    for name, stage in msvc.items():
        fix = fixes.get(name) or fixes.get(f'{name}_msvc')
        if fix is None:
            raise Fault(f'the MSVC case {name} has no fix in crypto.json')
        windows.append([code(name), f'the {stage}', fix])
    text += ('\nOn MSVC, each case of `test/msvc` is proven to stop the build, at compile or '
             'at link time; its text is MSVC\'s own, the same instruction in MSVC\'s words, and '
             'two files compiled with different settings stop the link with LNK2038.\n\n')
    text += table(['Case', 'Stops', 'Fix'], windows, 'cols="1,1,4",')
    return text


def use_cases_page(data: Data, library: Path) -> str:
    """The decision table: what a program needs, and what to use."""
    rows: List[List[str]] = []
    for entry in data['use_cases']:
        example = entry['example']
        if example and not (library / 'example' / f'{example}.cpp').is_file():
            raise Fault(f'crypto.json: the use case "{entry["need"]}" names the example '
                        f'{example}, which example/ does not hold')
        shown = (f'<<{entry["section"]},{code(f"example/{example}.cpp")}>>' if example
                 else f'<<{entry["section"]}>>')
        rows.append([entry['need'], entry['namespace'], code(entry['api']), entry['backend'],
                     code(entry['jamfile']), shown])
    return table(['I need to', 'Namespace', 'Use', 'Backend', 'Jamfile', 'Example'], rows,
                 'cols="3,2,3,2,3,2",')


HEADER = re.compile(r'<(webcpp/crypto/[\w/]+\.hpp)>')
# A reference to a line of a header, "(`include/secp256k1.h:235-247`)": the headers' own
# business, and stale once the line moves, so llms.txt leaves it out.
LINE_REFERENCE = re.compile(r'\s*\(`[\w./-]+:\d+(?:-\d+)?`\)')
DOC_COMMENT = re.compile(r'/\*\*(.*?)\*/', re.S)


def declared_brief(library: Path, operation: Data, function: str) -> str:
    """The first sentence of the Doc Comment of a function an operation names, read from the
    operation's headers: the description llms.txt gives it. A function no header declares is a
    fault."""
    if function == 'operator()':
        pattern = re.compile(r'\boperator\(\)\(')
    else:
        pattern = re.compile(rf'(?:\b{re.escape(function)}|\({re.escape(function)}\))\s*\(')
    for header in HEADER.findall(operation['header']):
        text = (library / 'include' / header).read_text(encoding='utf-8')
        for comment in DOC_COMMENT.finditer(text):
            rest = text[comment.end():]
            declaration = rest[:rest.find('{') if '{' in rest else len(rest)]
            declaration = declaration.split(';', 1)[0]
            declaration = '\n'.join(line.split('//', 1)[0] for line in declaration.splitlines())
            free = not declaration.lstrip('\n').startswith(' ')
            if operation.get('free') and not free:
                continue
            found = pattern.search(declaration)
            # The declared name: the first parenthesis of the declaration is its own.
            if found and '(' not in declaration[:found.start()] and '/*' not in declaration:
                words = ' '.join(line.strip().lstrip('*').strip()
                                 for line in comment.group(1).splitlines()).strip()
                words = LINE_REFERENCE.sub('', words.replace('@ref ', ''))
                return re.split(r'(?<=\.)\s', words, maxsplit=1)[0]
    raise Fault(f'crypto.json names {function} of {operation["id"]}, which no Doc Comment of '
                f'{operation["header"]} declares')


def first_comment(source: Path) -> str:
    """The comment that opens an example after its licence: what the program does."""
    lines = source.read_text(encoding='utf-8').splitlines()[6:]
    words: List[str] = []
    for line in lines:
        if not line.startswith('//') or line.startswith('// tag::'):
            break
        words.append(line[2:].strip())
    return ' '.join(words)


def llms(data: Data, matrix: Matrix, library: Path) -> str:
    """The index for LLMs, in the llms.txt form: what crypto offers, where, and for what."""
    page = data['page']
    out = ['# webcpp::crypto', '',
           '> Cryptographic primitives for C++20 on native, wasip2, wasip3 and Emscripten: '
           'AES-GCM, the AES block cipher, secp256k1 (BIP 340 Schnorr, ECDSA, ECDH, the x-only '
           'tweak), a random_device on the system\'s generator and a constant-time equal, each '
           'over a widely used, reviewed C library (BearSSL, OpenSSL, ctaes, libsecp256k1) that '
           'the program names in its Jamfile. Hashing and HMAC are Boost.Hash2\'s. Every '
           'failure is a boost::system::result value. Protocols (Bitcoin, Ethereum, Nostr) '
           'belong to domain libraries built on these primitives.', '',
           f'Generated by doc/tables/generate.py with the page\'s tables. Page: {page}', '']
    for namespace, title in NAMESPACE_TITLES.items():
        out += [f'## {title}', '']
        for operation in data['operations']:
            if operation['namespace'] != namespace:
                continue
            backends = '; '.join(
                f'{data["backends"][backend]["title"]} ({data["backends"][backend]["jamfile"]}) '
                f'on {", ".join(matrix.supported[(operation["id"], backend)])}'
                for backend in matrix.backends_of(operation['id'])
                if (operation['id'], backend) in matrix.supported)
            out.append(f'- [{operation["api"]}]({page}#{operation["section"]}): '
                       f'{operation["what"]} Header {operation["header"]}. Backends: {backends}.')
            for function in operation['functions']:
                out.append(f'  - {function}: '
                           f'{declared_brief(library, operation, function)}')
        out.append('')
    out += ['## Default backend of aes128_gcm, aes256_gcm and aes256<>', '']
    for entry in data['defaults']:
        out.append(f'- {entry["target"]}, linked {entry["linked"]}: '
                   f'{data["backends"][entry["default"]]["title"]}.')
    out += ['', '## Choose by use case', '']
    for entry in data['use_cases']:
        example = f' Example: example/{entry["example"]}.cpp.' if entry['example'] else ''
        out.append(f'- [{entry["need"]}]({page}#{entry["section"]}): {entry["api"]} '
                   f'({entry["namespace"]}); backend {entry["backend"]}; Jamfile '
                   f'{entry["jamfile"]}.{example}')
    out += ['', '## Examples', '']
    for source in sorted((library / 'example').glob('*.cpp')):
        out.append(f'- example/{source.name}: {first_comment(source)}')
    out += ['', '## Optional', '',
            f'- [Every message and its fix]({page}#crypto-jamfile-messages)',
            f'- [The backends]({page}#crypto-backends)',
            f'- [Reference]({page}#reference)', '']
    return '\n'.join(out)


def generate(root: Path, library: Path) -> Dict[Path, str]:
    """Every generated file, by its path, with its content."""
    data: Data = json.loads((HERE / 'crypto.json').read_text(encoding='utf-8'))
    declared = tests(library)
    refusals = messages(library)
    cases = fixtures(root)
    for name in cases:
        if name not in data['fixtures']:
            raise Fault(f'the fixture {name} names crypto and crypto.json does not describe it')
    for name in data['fixtures']:
        if name not in cases:
            raise Fault(f'crypto.json describes the fixture {name}, which the tree does not hold')
    matrix = Matrix(data, declared, refusals)
    generated = DOC / 'generated'
    files: Dict[Path, str] = {}
    for namespace in NAMESPACE_TITLES:
        files[generated / f'namespace-{namespace}.adoc'] = namespace_page(data, namespace)
    for operation in data['operations']:
        files[generated / f'backends-{operation["id"]}.adoc'] = api_backends(data, matrix,
                                                                             operation)
    files[generated / 'matrix.adoc'] = matrix_page(data, matrix)
    files[generated / 'backend-facts.adoc'] = facts_page(data, matrix)
    files[generated / 'defaults.adoc'] = defaults_page(data, declared)
    files[generated / 'constant-time.adoc'] = constant_time_page(data)
    files[generated / 'sizes.adoc'] = sizes_page(data)
    files[generated / 'jamfiles.adoc'] = jamfiles_page(data, cases)
    files[generated / 'messages.adoc'] = messages_page(data, refusals, cases,
                                                       msvc_cases(library))
    files[generated / 'use-cases.adoc'] = use_cases_page(data, library)
    for path in list(files):
        files[path] = NOTICE + files[path]
    files[DOC / 'llms.txt'] = llms(data, matrix, library)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or '').split('\n', 1)[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=LIBRARY.parent.parent)
    arguments = parser.parse_args()
    try:
        files = generate(arguments.root.resolve(), LIBRARY)
    except Fault as fault:
        print(f'generate.py: {fault}', file=sys.stderr)
        return 1
    stale = sorted(path for path, text in files.items()
                   if not path.is_file() or path.read_text(encoding='utf-8') != text)
    extra = sorted(path for path in (DOC / 'generated').glob('*.adoc') if path not in files)
    if arguments.check:
        for path in stale:
            print(f'generate.py: {path.relative_to(LIBRARY)} is not what crypto.json and the '
                  'tree give: run python3 libs/crypto/doc/tables/generate.py', file=sys.stderr)
        for path in extra:
            print(f'generate.py: {path.relative_to(LIBRARY)} is generated by nothing: remove it',
                  file=sys.stderr)
        return 1 if stale or extra else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding='utf-8')
    for path in extra:
        path.unlink()
    return 0


if __name__ == '__main__':
    sys.exit(main())
