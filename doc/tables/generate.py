class Fault(Exception):
    """A fact of crypto.json that the tree does not hold, or the reverse."""


def statements(jamfile: Path) -> List[List[List[str]]]:
    """Each statement of a Jamfile at its top level, its words cut into fields at each `:`.

    The body of a rule is skipped: it declares nothing until the rule is called. A program
    declared inside another block, an `if` or a `for`, is a fault: its targets would depend on
    a condition this reading does not evaluate, and the tables would say it runs everywhere.
    """
    words: List[str] = []
    for line in jamfile.read_text(encoding='utf-8').splitlines():
        words += line.split('#', 1)[0].split()
    found: List[List[List[str]]] = []
    current: List[List[str]] = [[]]
    blocks: List[str] = []
    for word in words:
        if word == '{':
            blocks.append('rule' if current[0][:1] == ['rule'] else 'other')
            current = [[]]
        elif word == '}':
            if blocks:
                blocks.pop()
            current = [[]]
        elif word == ';':
            head = current[0]
            if head and head[0] in RUN_RULES and 'other' in blocks and 'rule' not in blocks:
                raise Fault(f'{jamfile}: {head[0]} {head[1:2]} is declared inside a block, '
                            'which generate.py does not evaluate')
            if current != [[]] and not blocks:
                found.append(current)
            current = [[]]
        elif word == ':':
            current.append([])
        else:
            current[-1].append(word)
    return found


def programs(jamfile: Path, inherited: Optional[List[str]] = None) -> Dict[str, List[str]]:
    """The targets of each program a Jamfile declares with webcpp's rules, by its name."""
    default = list(inherited or ['native'])
    found: Dict[str, List[str]] = {}
    for fields in statements(jamfile):
        head = fields[0]
        if head and head[0] == 'webcpp.targets':
            default = head[1:]
        elif head and head[0] in RUN_RULES and len(head) > 1:
            targets = fields[3] if len(fields) > 3 and fields[3] else default
            found[head[1]] = list(targets)
    return found


def tests(library: Path) -> Dict[str, List[str]]:
    """Every program of the test Jamfile, of each message test and of the OpenSSL memory
    option's tests (test/openssl_memory), with its targets. A name two Jamfiles declare is a
    fault: a table that cites it would name one of two programs."""
    found: Dict[str, List[str]] = {}
    test = library / 'test'
    jamfiles = [test / 'Jamfile', *sorted((test / 'messages').glob('*/Jamfile'))]
    if (test / 'openssl_memory' / 'Jamfile').is_file():
        jamfiles.append(test / 'openssl_memory' / 'Jamfile')
    for jamfile in jamfiles:
        for name, targets in programs(jamfile).items():
            if name in found:
                raise Fault(f'{jamfile}: the test {name} is declared twice')
            found[name] = targets
    return found


def messages(library: Path) -> Dict[str, Tuple[str, List[str]]]:
    """Each message test's case: the text its source states, and its targets."""
    found: Dict[str, Tuple[str, List[str]]] = {}
    for directory in sorted((library / 'test' / 'messages').iterdir()):
        if not directory.is_dir():
            continue
        declared = programs(directory / 'Jamfile')
        for source in sorted(directory.glob('*.cpp')):
            for line in source.read_text(encoding='utf-8').splitlines():
                text = EXPECTED_ERROR.search(line)
                if text and source.stem in declared:
                    found[source.stem] = (text.group(1), declared[source.stem])
    return found


def msvc_cases(library: Path) -> Dict[str, str]:
    """Each MSVC case, and whether it stops at compile or at link time."""
    found: Dict[str, str] = {}
    for jamfile in sorted((library / 'test' / 'msvc').glob('*/Jamfile')):
        for fields in statements(jamfile):
            head = fields[0]
            if head and head[0] in ('webcpp.compile-fail', 'webcpp.link-fail'):
                found[head[1]] = 'compile' if head[0] == 'webcpp.compile-fail' else 'link'
    return found


class Outcome:
    """A fixture's .outcome: its targets, whether it builds, whether its program runs, what it
    prints or contains. A fixture that builds and runs nothing is a record: a misuse that only
    MSVC's linker stops, which links elsewhere."""

    def __init__(self, path: Path) -> None:
        self.targets: List[str] = []
        self.succeeds = False
        self.runs = False
        self.output: List[str] = []
        self.contains: List[Tuple[str, str]] = []
        self.absent: List[Tuple[str, str]] = []
        section = 'all'
        printing = False
        for line in path.read_text(encoding='utf-8').splitlines():
            if not line or line.startswith('#'):
                continue
            if line.startswith('[') and line.endswith(']'):
                section = line[1:-1]
                printing = False
            elif line.startswith('targets:'):
                self.targets = line.split()[1:]
            elif line.startswith('build:'):
                self.succeeds = line.split()[1] == 'succeeds'
            elif line.startswith('run:'):
                self.runs = printing = True
            elif line.startswith('contains:'):
                self.contains.append((section, line[len('contains:'):].strip()))
            elif line.startswith('not-contains:'):
                self.absent.append((section, line[len('not-contains:'):].strip()))
            elif printing:
                self.output.append(line)


def fixtures(root: Path) -> Dict[str, Tuple[List[str], Outcome]]:
    """Each fixture of the user's Jamfiles that names crypto: its Jamfile's lines, its outcome."""
    found: Dict[str, Tuple[List[str], Outcome]] = {}
    directory = root / FIXTURES
    for case in sorted(path for path in directory.iterdir() if path.is_dir()):
        jamfile = case / 'Jamfile'
        lines = [line for line in jamfile.read_text(encoding='utf-8').splitlines()
                 if line.strip() and not line.startswith('#')]
        if not any('/webcpp/crypto//crypto' in line for line in lines):
            continue
        outcome = Outcome(case / f'{case.name}.outcome')
        regions = [('Jamfile', 'jamfile')]
        if outcome.succeeds and outcome.runs:
            regions.append((f'{case.name}.outcome', 'output'))
        for file, wanted in regions:
            text = (case / file).read_text(encoding='utf-8')
            if f'tag::{wanted}[]' not in text or f'end::{wanted}[]' not in text:
                raise Fault(f'the fixture {case.name}: {file} has no region {wanted}, which '
                            'the page includes')
        found[case.name] = (lines, outcome)
    return found


def cite(data: Data, text: str) -> str:
    """text with each {source} written as a link to the source crypto.json names."""
    def link(match: 're.Match[str]') -> str:
        source = data['sources'].get(match.group(1))
        if source is None:
            raise Fault(f'crypto.json names the source {match.group(1)}, which it does not list')
        return f'link:{source[1]}[{source[0]}]'
    return SOURCE.sub(link, text)


def cite_markdown(data: Data, text: str) -> str:
    """text with each {source} written as a Markdown link to the source crypto.json names, as
    llms.txt writes links."""
    def link(match: 're.Match[str]') -> str:
        source = data['sources'].get(match.group(1))
        if source is None:
            raise Fault(f'crypto.json names the source {match.group(1)}, which it does not list')
        return f'[{source[0]}]({source[1]})'
    return SOURCE.sub(link, text)


def cell(text: str) -> str:
    """text made safe in a cell of a table: no | read as the cell's end."""
    return text.replace('|', '\\|')


def code(text: str) -> str:
    """text as inline code, every character as it is. A text that holds a `+` or a backtick is
    a raw passthrough inside the code, its HTML written here: a `+` would end a constrained one,
    `+em++: error:+` read as `+em+` and the rest, and a backtick is written as the reference
    the page keeps for it, as a literal one reads as two spans run together."""
    if '+' in text or '`' in text:
        escaped = (text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                   .replace('`', '&#96;').replace(']', '\\]'))
        return f'`pass:[{escaped}]`'
    return f'`+{text}+`'


# A name in crypto.json's text, `between backticks`, as Markdown writes code: llms.txt keeps it.
TICKED = re.compile(r'`([^`]+)`')


def kept(text: str) -> str:
    """text as inline code the page keeps on one line at every width, a file a reader copies
    (the role keep, tools/doc/docinfo.html)."""
    return f'[.keep]{code(text)}'


def marked(text: str) -> str:
    """text of crypto.json with each name between backticks written as inline code."""
    return TICKED.sub(lambda match: code(match.group(1)), text)


def names(text: str) -> str:
    """A list of names, "ciphers::gcm, aes128_gcm", each as inline code of its own, so that
    the list breaks between its names as a sentence does."""
    return ', '.join(code(name) for name in text.split(', '))


def table(columns: List[str], rows: List[List[str]], style: str = '') -> str:
    """An AsciiDoc table with a header row."""
    head = f'[{style}options="header"]\n' if style else '[options="header"]\n'
    lines = [head + '|===']
    lines.append(' '.join(f'|{cell(column)}' for column in columns))
    for row in rows:
        lines.append('')
        lines.extend(value if value.startswith('a|') else f'|{value}' for value in row)
    lines.append('|===')
    return '\n'.join(lines) + '\n'


class Matrix:
    """The support of each operation on each backend and target, from the tests' targets."""

    def __init__(self, data: Data, declared: Dict[str, List[str]],
                 refusals: Dict[str, Tuple[str, List[str]]]) -> None:
        self.data = data
        self.supported: Dict[Tuple[str, str], List[str]] = {}
        self.proofs: Dict[Tuple[str, str], List[str]] = {}
        self.refused: Dict[Tuple[str, str], str] = {}
        # Why an operation is missing on the targets its tests leave out, when it is not the
        # backend's own reason: a key of crypto.json's elsewhere.
        self.elsewhere: Dict[Tuple[str, str], str] = {}
        for operation in data['operations']:
            for backend, entry in operation['backends'].items():
                key = (operation['id'], backend)
                if 'tests' in entry:
                    targets: List[str] = []
                    for name in entry['tests']:
                        if name not in declared:
                            raise Fault(f'crypto.json: {operation["id"]} on {backend} names the '
                                        f'test {name}, which no test Jamfile declares')
                        targets += declared[name]
                    self.supported[key] = [target for target in data['targets']
                                           if target in targets]
                    self.proofs[key] = list(entry['tests'])
                    if 'elsewhere' in entry:
                        # Only OpenSSL's cells name what stops an operation elsewhere
                        # (targets()); another backend's reason would never be shown.
                        if backend != 'openssl':
                            raise Fault(f'crypto.json: {operation["id"]} on {backend} names '
                                        f'the reason {entry["elsewhere"]}, which only '
                                        'OpenSSL\'s entries may give')
                        if entry['elsewhere'] not in data['elsewhere']:
                            raise Fault(f'crypto.json: {operation["id"]} on {backend} names '
                                        f'the reason {entry["elsewhere"]}, which elsewhere '
                                        'does not hold')
                        self.elsewhere[key] = entry['elsewhere']
                else:
                    if entry['refused'] not in refusals:
                        raise Fault(f'crypto.json: {operation["id"]} on {backend} is refused by '
                                    f'{entry["refused"]}, which no message test declares')
                    self.refused[key] = entry['refused']

    def backends_of(self, operation: str) -> List[str]:
        """The backends that implement or refuse an operation, in the page's order."""
        return [backend for backend in BACKEND_ORDER
                if (operation, backend) in self.supported or (operation, backend) in self.refused]

    def targets_of(self, backend: str) -> List[str]:
        """Every target on which a backend implements something."""
        found = {target for (_, name), targets in self.supported.items() if name == backend
                 for target in targets}
        return [target for target in self.data['targets'] if target in found]

    def targets(self, operation: str, backend: str) -> str:
        """A cell: the targets an operation runs on with a backend, or that it is refused."""
        key = (operation, backend)
        if key in self.refused:
            return self.data['elsewhere']['refused']
        text = ', '.join(self.supported[key])
        missing = [target for target in self.data['targets']
                   if target not in self.supported[key]]
        if missing and backend == 'openssl':
            reason = self.elsewhere.get(key, 'openssl')
            text += f'; not on {", ".join(missing)}: {marked(self.data["elsewhere"][reason])}'
        return text

    def tests(self, operation: str, backend: str) -> str:
        """A cell: the tests that run an operation on a backend, or the message test that
        refuses it."""
        key = (operation, backend)
        if key in self.refused:
            return code(self.refused[key])
        return ', '.join(code(name) for name in self.proofs[key])

    def describe(self, operation: str, backend: str) -> str:
        """A cell: the targets an operation runs on with a backend and the tests that run it, or
        the message test that refuses it."""
        key = (operation, backend)
        if key in self.refused:
            return f'{self.targets(operation, backend)} ({self.tests(operation, backend)})'
        targets = ', '.join(self.supported[key])
        text = f'{targets} (tested by {self.tests(operation, backend)})'
        rest = self.targets(operation, backend)[len(targets):]
        return text + rest


def tags_of(data: Data) -> List[str]:
    """The backends that are tags of `backends`, in crypto.json's order: those built for targets
    of their own, where the rest (the system's generator, no backend at all) are not."""
    return [name for name, facts in data['backends'].items() if 'targets' in facts]


def cell_targets(data: Data, family: Data, backend: str) -> List[str]:
    """The targets on which a backend has a family, in crypto.json's order of targets: "all" is
    every target the backend is built for."""
    wanted = family['backends'][backend]['targets']
    if wanted == 'all':
        wanted = data['backends'][backend]['targets']
    return [target for target in data['targets'] if target in wanted]


def check_families(data: Data, declared: Dict[str, List[str]]) -> None:
    """Checks crypto.json's families against its backends, its operations and the tests: a cell is
    claimed only for a tag of `backends`, on a target it is built for and where a test of the
    family's operations on it runs; each target has one default, a backend that has the family
    there, or none."""
    names = {family['name'] for family in data['families']}
    for operation in data['operations']:
        if 'family' in operation and operation['family'] not in names:
            raise Fault(f'crypto.json: the operation {operation["id"]} names the family '
                        f'{operation["family"]}, which crypto.json does not list')
    tags = tags_of(data)
    for family in data['families']:
        name = family['name']
        for backend, entry in family['backends'].items():
            if backend not in tags:
                raise Fault(f'crypto.json: the family {name} names the backend {backend}, which '
                            'is no tag of backends')
            built = data['backends'][backend]['targets']
            claimed = built if entry['targets'] == 'all' else entry['targets']
            tested: List[str] = []
            for operation in data['operations']:
                if operation.get('family') == name:
                    for test in operation['backends'].get(backend, {}).get('tests', []):
                        tested += declared.get(test, [])
            for target in claimed:
                if target not in built:
                    raise Fault(f'crypto.json: the family {name} claims {backend} on {target}, '
                                f'where {backend} is not built')
                if target not in tested:
                    raise Fault(f'crypto.json: the family {name} claims {backend} on {target}, '
                                f'where no test of its operations on {backend} runs')
            for target, why in entry.get('constant_time', {}).items():
                if target not in claimed:
                    raise Fault(f'crypto.json: the family {name} states constant time for '
                                f'{backend} on {target}, where it does not claim it')
                cite(data, why)
        # One default per target, chosen by the target alone (design D32): a row of some
        # compilers, named from crypto.json's compilers, restates it with a reason of its own, and
        # each compiler of a target has one row. Each is claimed only where a test that fixes it
        # runs.
        rows: List[Tuple[str, str]] = []
        for entry in family['default']:
            cite(data, entry['why'])
            backend = entry['backend']
            for target in entry['targets']:
                for compiler in entry.get('compilers', data['compilers']):
                    if compiler not in data['compilers']:
                        raise Fault(f'crypto.json: the family {name}\'s default on {target} '
                                    f'names the compiler {compiler}, which crypto.json\'s '
                                    'compilers does not list')
                    if (target, compiler) in rows:
                        raise Fault(f'crypto.json: the family {name} has two defaults on '
                                    f'{target} with {compiler}')
                    rows.append((target, compiler))
                chosen = default_on(family, target)
                if chosen != backend:
                    raise Fault(f'crypto.json: the family {name} has two default backends on '
                                f'{target}, {chosen or "none"} and {backend or "none"}: the '
                                'target alone chooses it')
                if backend is not None and (backend not in family['backends'] or
                                            target not in cell_targets(data, family, backend)):
                    raise Fault(f'crypto.json: the family {name} defaults to {backend} on '
                                f'{target}, which does not have it there')
                for test in entry['tests']:
                    if target not in declared.get(test, []):
                        raise Fault(f'crypto.json: the family {name}\'s default on {target} '
                                    f'names the test {test}, which does not run there')
        if any(default_on(family, target) and
               others_of(data, family, target, default_on(family, target) or '')
               for target in data['targets']):
            if 'shown' not in family:
                raise Fault(f'crypto.json: the family {name} has no shown name, which its '
                            'default\'s refusal names with another backend')
            if family['shown'] not in [entry['name'] for entry in family['names']]:
                raise Fault(f'crypto.json: the family {name} shows {family["shown"]}, which is '
                            'none of its names')
        covered = {target for target, _ in rows}
        missing = [target for target in data['targets'] if target not in covered]
        if missing:
            raise Fault(f'crypto.json: the family {name} has no default on {", ".join(missing)}')
        for target in data['targets']:
            for compiler in data['compilers']:
                if (target, compiler) not in rows:
                    raise Fault(f'crypto.json: the family {name} has no default on {target} '
                                f'with {compiler}')


def default_on(family: Data, target: str) -> Optional[str]:
    """A family's default backend on a target, or None: its first row there (check_families
    faults a row that names another)."""
    for entry in family['default']:
        if target in entry['targets']:
            return entry['backend']
    return None


def have_list(data: Data, family: Data) -> str:
    """The backends that have a family, each with its targets, as a refusal names them."""
    parts: List[str] = []
    for backend, entry in family['backends'].items():
        late = ', at run time' if entry.get('runtime') else ''
        parts.append(f'{backend} ({", ".join(cell_targets(data, family, backend))}{late})')
    return ', '.join(parts)


def refusal(data: Data, family: Data, backend: str) -> str:
    """The refusal of a backend without a family (spec, "a backend without a function
    refuses")."""
    return (f'webcpp::crypto: {backend} has no {family["title"]}. The backends that have it: '
            f'{have_list(data, family)}.')


def tag_of(family: Data, name: str) -> str:
    """The tag of an algorithm: a family of one algorithm of its own name is its own tag."""
    return f'families::{name}' if name == family['name'] else f'tags::{name}'


def doc_comment(text: str) -> List[str]:
    """A Doc Comment's lines, as clang-format leaves them: on one line where it fits in 100
    columns, else broken between words."""
    if len(text) + 7 <= 100:
        return [f'/** {text} */']
    return ['/**'] + [f' * {line}' for line in textwrap.wrap(text, 97)] + [' */']


def program_type(data: Data, written: str, backend: str) -> str:
    """A type of crypto.json, written from webcpp::crypto, as the generated test names it: each
    of crypto's namespaces that starts a name is reached through `crypto::`, and `{backend}` is
    the backend's tag. Any other namespace, std:: among them, is left as it is."""
    namespaces = ({name for name in data.get('namespaces', {}) if name != 'root'}
                  | {family['group'].split('::')[0] for family in data['families']})
    qualified = re.compile(rf'(?<![\w:])((?:{"|".join(sorted(namespaces))})::)')
    return qualified.sub(r'crypto::\1', written).replace('{backend}', f'backends::{backend}')


def condition(targets: List[str]) -> str:
    """The preprocessor's condition that holds on the targets."""
    return ' || '.join(f'defined({TARGET_MACROS[target]})' for target in targets)


def opening(targets: List[str], first: bool = True) -> str:
    """The directive that opens, or with first false continues, a block that holds on the
    targets: #ifdef for one target where it opens one, as clang-tidy's
    readability-use-concise-preprocessor-directives asks."""
    if not first:
        return f'#elif {condition(targets)}'
    if len(targets) == 1:
        return f'#ifdef {TARGET_MACROS[targets[0]]}'
    return f'#if {condition(targets)}'


def capabilities_header(data: Data) -> str:
    """include/webcpp/crypto/detail/capabilities.hpp: the family and algorithm tags, each cell of
    `detail::supported` on its targets, and the refusals of each family's primary engine."""
    out = ['#ifndef WEBCPP_CRYPTO_DETAIL_CAPABILITIES_HPP',
           '#define WEBCPP_CRYPTO_DETAIL_CAPABILITIES_HPP', '',
           '#include <webcpp/crypto/config.hpp>', '',
           '#include <webcpp/crypto/detail/engines.hpp>', '',
           '#include <type_traits>', '',
           'namespace webcpp::crypto::families {', '']
    named: List[Tuple[Data, Data]] = []
    for family in data['families']:
        algorithms = [entry['name'] for entry in family['names']]
        listed = ', '.join(f'`{tag_of(family, name)}`' for name in algorithms)
        if algorithms == [family['name']]:
            text = (f'The family {family["title"]}, of `{family["group"]}`, also the tag of its '
                    'one algorithm.')
        else:
            text = (f'The family {family["title"]}, of `{family["group"]}`; its algorithms: '
                    f'{listed}.')
        out += doc_comment(text) + [f'struct {family["name"]};', '']
        named += [(family, entry) for entry in family['names'] if entry['name'] != family['name']]
    out += ['}  // namespace webcpp::crypto::families', '']
    if named:
        out += ['namespace webcpp::crypto::tags {', '']
        for family, entry in named:
            out += doc_comment(f'{entry["title"]}, of the family '
                               f'`families::{family["name"]}`.') + [f'struct {entry["name"]};',
                                                                    '']
        out += ['}  // namespace webcpp::crypto::tags', '']
    out += ['namespace webcpp::crypto::detail {', '',
            '/**',
            ' * One cell of the capability table, doc/tables/crypto.json, on the target being',
            ' * compiled: whether `Backend` has the algorithm `Name` of the family `Family`. False',
            ' * but where a specialisation below makes it true.',
            ' *',
            ' * @tparam Family A family tag of `families`.',
            ' * @tparam Name An algorithm\'s tag of `tags`, or the family\'s own tag for a',
            ' * family of one algorithm.',
            ' * @tparam Backend A backend tag of `backends`.',
            ' */',
            'template <class Family, class Name, class Backend>',
            'inline constexpr bool supported = false;', '',
            '// Each cell on its targets, as long as the table\'s names make its line.',
            '// clang-format off']
    for family in data['families']:
        for backend in family['backends']:
            targets = cell_targets(data, family, backend)
            out.append(f'// {family["title"]} on {backend}: {", ".join(targets)}.')
            for entry in family['names']:
                out += [opening(targets), 'template <>',
                        f'inline constexpr bool supported<families::{family["name"]}, '
                        f'{tag_of(family, entry["name"])}, backends::{backend}> = true;',
                        '#endif']
    out += ['// clang-format on', '',
            '/**',
            ' * Whether `Backend`\'s library is linked: its `WEBCPP_CRYPTO_HAS_<NAME>` is defined.',
            ' *',
            ' * @tparam Backend A backend tag of `backends`.',
            ' */',
            'template <class Backend>', 'inline constexpr bool linked = false;']
    for backend in tags_of(data):
        out += [f'#ifdef WEBCPP_CRYPTO_HAS_{backend.upper()}', 'template <>',
                f'inline constexpr bool linked<backends::{backend}> = true;', '#endif']
    out += ['', '}  // namespace webcpp::crypto::detail', '',
            '// The body of each family\'s primary engine, which a backend reaches where its',
            '// header does not specialise the engine, per target: a backend without the family',
            '// there is refused, naming those that have it; the default there, not linked, says',
            '// the Jamfile line that links it and the type that names another backend; a backend',
            '// that has it there, whose header the program did not include, is told to include',
            '// it; any other type is no backend of the family.',
            '// clang-format off']
    tags = tags_of(data)
    for family in data['families']:
        have = have_list(data, family)
        known = ' || '.join(f'std::is_same_v<Backend, ::webcpp::crypto::backends::{backend}>'
                            for backend in tags)
        for index, target in enumerate(data['targets']):
            lines: List[str] = []
            for backend in tags:
                tag = f'::webcpp::crypto::backends::{backend}'
                if backend not in family['backends']:
                    lines.append(f'static_assert(!std::is_same_v<Backend, {tag}>, '
                                 f'"{refusal(data, family, backend)}")')
                    continue
                if target not in cell_targets(data, family, backend):
                    lines.append(f'static_assert(!std::is_same_v<Backend, {tag}>, '
                                 f'"webcpp::crypto: {backend} has no {family["title"]} on '
                                 f'{target}. The backends that have it: {have}.")')
                    continue
                facts = data['backends'][backend]
                include = (f'webcpp::crypto: {backend}\'s {family["title"]} is in '
                           f'{facts["header"]}, which the program does not include. Include '
                           f'it, and add {facts["jamfile"]} to the program\'s Jamfile.')
                if backend != default_on(family, target):
                    lines.append(f'static_assert(!std::is_same_v<Backend, {tag}>, "{include}")')
                    continue
                # The default: not linked, what the program needs; linked, its header.
                linked = f'::webcpp::crypto::detail::linked<{tag}>'
                lines += [f'static_assert(!std::is_same_v<Backend, {tag}> || {linked}, '
                          f'"{needs(data, family, target, backend)}")',
                          f'static_assert(!std::is_same_v<Backend, {tag}> || !{linked}, '
                          f'"{include}")']
            lines.append(f'static_assert({known}, "webcpp::crypto: {family["title"]} has no '
                         f'backend of that name. The backends that have it: {have}.")')
            out.append(opening([target], index == 0))
            out += doc_comment(f'The refusals of the family {family["title"]}\'s primary engine '
                               f'for `Backend`, on {target}.') + [
                    f'#define WEBCPP_CRYPTO_DETAIL_REFUSE_{family["name"].upper()}(Backend) \\']
            out += [f'    {line}; \\' for line in lines[:-1]] + [f'    {lines[-1]}']
        out.append('#endif')
    out += ['// clang-format on', '', '#endif  // WEBCPP_CRYPTO_DETAIL_CAPABILITIES_HPP', '']
    return '\n'.join(out)


def others_of(data: Data, family: Data, target: str, backend: str) -> List[str]:
    """The backends other than backend that have a family on a target when the program is built,
    in crypto.json's order of backends: a cell decided at run time is not one a program can be
    sure to get."""
    return [other for other in tags_of(data)
            if other != backend and other in family['backends']
            and not family['backends'][other].get('runtime')
            and target in cell_targets(data, family, other)]


def needs(data: Data, family: Data, target: str, backend: str) -> str:
    """What a program that uses a family's default without linking it needs (design D32): the
    Jamfile line that links it, the family's alias /webcpp/crypto//<family>-default (which
    default_aliases writes), and, where another backend has the family on the target, the type
    that names the first of them (others_of) in the family's shown name; then, as every message
    of a backend not linked, what a build without b2 defines and links. The text holds on every
    target where the default is that backend, so that one message test checks it on each."""
    facts = data['backends'][backend]
    head = (f'webcpp::crypto: {family["title"]}\'s default backend on this target is '
            f'{facts["title"]}, which is not linked')
    alias = f'/webcpp/crypto//{family["name"]}-default'
    add = (f'Add {alias}, the default\'s library on every target, to the program\'s Jamfile, as '
           f'in: exe app : app.cpp /webcpp/crypto//crypto {alias} ;')
    without = (f'(without b2: define WEBCPP_CRYPTO_HAS_{backend.upper()}=1 and '
               f'{facts["without_b2"]})')
    others = others_of(data, family, target, backend)
    if not others:
        return f'{head}, and the one backend that has it there. {add} {without}'
    shown = next(entry for entry in family['names'] if entry['name'] == family['shown'])
    named = shown['type'].replace('{backend}', f'backends::{others[0]}')
    return (f'{head}. {add} or name another backend in the type, as in {named}. The backends '
            f'that have it: {have_list(data, family)}. {without}')


def default_aliases(data: Data) -> str:
    """The block of build.jam that gives each family with a default the alias
    /webcpp/crypto//<family>-default, which links the library of its default on each target,
    as detail/defaults.hpp chooses it: one Jamfile line for a program built for every target."""
    out = [ALIASES_BEGIN,
           '# Generated by doc/tables/generate.py from doc/tables/crypto.json: run it',
           '# again, never edit this block. Each family with a default backend has the',
           '# alias /webcpp/crypto//<family>-default, which links the library of its',
           '# default on each target, the backend detail/defaults.hpp chooses there.']
    for family in data['families']:
        cases = [(target, default_on(family, target)) for target in data['targets']]
        if not any(backend for _, backend in cases):
            continue
        name = family['name']
        out += [f'rule {name}-default-linked ( properties * )', '{',
                '    switch [ webcpp-target.target-of $(properties) ]', '    {']
        out += [f'        case {target} : return <library>{data["backends"][backend]["jamfile"]} ;'
                for target, backend in cases if backend]
        out += ['    }', '}',
                f'alias {name}-default : : : : <conditional>@{name}-default-linked ;']
    out.append(ALIASES_END)
    return '\n'.join(out) + '\n'


def aliases_page(data: Data, cases: Dict[str, Tuple[List[str], Outcome]]) -> str:
    """The table of the aliases default_aliases writes: per family with a default, its alias
    /webcpp/crypto//<family>-default, the library it links on each target, and the fixture of the
    user's Jamfiles that builds and runs it, <family>_default, which must build and run on every
    target where the family has a default: a public name that no build reaches is a fault."""
    rows: List[List[str]] = []
    for family in data['families']:
        cases_of = [(target, default_on(family, target)) for target in data['targets']]
        if not any(backend for _, backend in cases_of):
            continue
        name = family['name']
        alias = f'/webcpp/crypto//{name}-default'
        fixture = f'{name}_default'
        if fixture not in cases or not cases[fixture][1].succeeds:
            raise Fault(f'the alias {alias} has no fixture {fixture} that builds it')
        missing = [target for target, backend in cases_of
                   if backend and target not in cases[fixture][1].targets]
        if missing:
            raise Fault(f'the fixture {fixture} does not run on {", ".join(missing)}, where '
                        f'{family["title"]} has a default')
        # The targets of each library, in the order of their first target: one cell that
        # says "on every target" when one library serves them all.
        grouped: Dict[str, List[str]] = {}
        for target, backend in cases_of:
            if backend:
                grouped.setdefault(data['backends'][backend]['jamfile'], []).append(target)
        links = '; '.join(
            f'{code(jamfile)} on '
            f'{"every target" if targets == data["targets"] else ", ".join(targets)}'
            for jamfile, targets in grouped.items())
        rows.append([code(alias), family['title'], links,
                     f'<<crypto-jamfile-cases,{code(fixture)}>>'])
    return table(['Alias', 'Family', 'Links', 'Fixture'], rows, 'cols="3,2,4,3",')


def with_aliases(text: str, block: str) -> str:
    """build.jam's text with its block of the defaults' aliases replaced by block."""
    lines = text.splitlines(keepends=True)
    try:
        begin = lines.index(ALIASES_BEGIN + '\n')
        end = lines.index(ALIASES_END + '\n')
    except ValueError:
        raise Fault(f'build.jam has no block between "{ALIASES_BEGIN}" and "{ALIASES_END}"') \
            from None
    return ''.join(lines[:begin]) + block + ''.join(lines[end + 1:])


def defaults_header(data: Data) -> str:
    """include/webcpp/crypto/detail/defaults.hpp: each family's default backend per target,
    chosen by the target alone (design D32), and the macro that tells the family's header which
    backend's header to include."""
    out = ['#ifndef WEBCPP_CRYPTO_DETAIL_DEFAULTS_HPP', '#define WEBCPP_CRYPTO_DETAIL_DEFAULTS_HPP',
           '', '#include <webcpp/crypto/config.hpp>', '',
           '#include <webcpp/crypto/detail/capabilities.hpp>', '',
           'namespace webcpp::crypto {', '',
           '/**',
           ' * The default backend of `Family` on the target being compiled, as its `type`.',
           ' *',
           ' * One per family and target, chosen by the target alone whatever the program links,',
           ' * for the reason doc/tables/crypto.json gives (the guide\'s "The default backend per',
           ' * target"). A family without a default has no `type`; a program names any other',
           ' * backend in the type.',
           ' *',
           ' * @tparam Family A family tag of `families`.',
           ' */',
           'template <class Family>', 'struct default_backend_of {};', '',
           '// Each family\'s default, on the targets where it is that backend.',
           '// clang-format off']
    for family in data['families']:
        groups: List[Tuple[str, List[str]]] = []
        for target in data['targets']:
            backend = default_on(family, target)
            if backend is None:
                continue
            for chosen, targets in groups:
                if chosen == backend:
                    targets.append(target)
                    break
            else:
                groups.append((backend, [target]))
        if not groups:
            continue
        conditional = len(groups) > 1 or len(groups[0][1]) < len(data['targets'])
        for index, (backend, targets) in enumerate(groups):
            title = data['backends'][backend]['title']
            if conditional:
                out.append(opening(targets, index == 0))
            out += doc_comment(f'Defined where {title} is the default of {family["title"]}.')
            out.append(f'#define WEBCPP_CRYPTO_DETAIL_DEFAULT_{family["name"].upper()}_'
                       f'{backend.upper()} 1')
            out += doc_comment(f'The default of {family["title"]} on {", ".join(targets)}: '
                               f'{title}.')
            out += ['template <>', f'struct default_backend_of<families::{family["name"]}> {{',
                    f'    /** `backends::{backend}`. */', f'    using type = backends::{backend};',
                    '};']
        if conditional:
            out.append('#endif')
    out += ['// clang-format on', '',
            '/**',
            ' * The default backend of `Family` on the target being compiled (see',
            ' * @ref default_backend_of).',
            ' *',
            ' * @tparam Family A family tag of `families` that has a default.',
            ' */',
            'template <class Family>',
            'using default_backend_t = default_backend_of<Family>::type;', '']
    if any(family['name'] == 'gcm' for family in data['families']):
        out += ['/**',
                ' * The default backend of AES-GCM, version 0.1\'s name, which `aes128_gcm`,',
                ' * `aes256_gcm` and the AES block cipher\'s `aes256<>` take: natively OpenSSL, on',
                ' * WebAssembly BearSSL.',
                ' *',
                ' * @see "The default backend per target", in the guide.',
                ' */',
                'using default_backend = default_backend_t<families::gcm>;', '']
    out += ['}  // namespace webcpp::crypto', '',
            '#endif  // WEBCPP_CRYPTO_DETAIL_DEFAULTS_HPP', '']
    return '\n'.join(out)


def capabilities_test(data: Data) -> str:
    """test/capabilities_test.cpp: `supports_v` of every cell on the target being compiled, each
    present cell made through its family's own type where its backend is linked, and each
    family's refusal parsed."""
    tags = tags_of(data)
    headers = sorted({family['header'] for family in data['families']}
                     | {'<webcpp/crypto/supports.hpp>', '<webcpp/test/exit_status.hpp>'})
    out = ['// What doc/tables/crypto.json says of each cell of the capability table, on the',
           '// target being compiled: supports_v of each algorithm on each backend, true on the',
           '// cell\'s targets alone; each present cell made, where its backend is linked, through',
           '// the type a program names, which names its family and its algorithm as the table',
           '// does; and each family\'s refusal, parsed.', '']
    out += [f'#include {header}' for header in headers] + ['']
    for backend in tags:
        out += [f'#ifdef WEBCPP_CRYPTO_HAS_{backend.upper()}',
                f'#include {data["backends"][backend]["header"]}', '#endif']
    out += ['', '#include "support/capabilities.hpp"', '',
            '#include <boost/core/lightweight_test.hpp>', '',
            'namespace {', '',
            'namespace crypto = webcpp::crypto;',
            'namespace backends = webcpp::crypto::backends;',
            'namespace families = webcpp::crypto::families;']
    if any(entry['name'] != family['name'] for family in data['families']
           for entry in family['names']):
        out.append('namespace tags = webcpp::crypto::tags;')
    out += ['', '/** An algorithm of `Family` named `Name`, as `supports_v` reads one. */',
            'template <class Family, class Name>', 'struct algorithm {',
            '    /** The family. */', '    using family_type = Family;',
            '    /** The algorithm. */', '    using name_type = Name;', '};']
    for family in data['families']:
        out += ['', f'/** The refusals of {family["title"]}, parsed: nothing instantiates it. */',
                'template <class Backend>', f'struct refuses_{family["name"]} {{',
                f'    WEBCPP_CRYPTO_DETAIL_REFUSE_{family["name"].upper()}(Backend);', '};']
    out += ['', '}  // namespace', '', '// clang-format off']
    made: List[str] = []
    for family in data['families']:
        for backend in tags:
            present = backend in family['backends']
            targets = cell_targets(data, family, backend) if present else []
            out.append(f'// {family["title"]} on {backend}: {", ".join(targets) or "none"}.')
            for entry in family['names']:
                tag = tag_of(family, entry['name'])
                trait = (f'crypto::supports_v<algorithm<families::{family["name"]}, {tag}>, '
                         f'backends::{backend}>')
                if not present:
                    out.append(f'static_assert(!{trait});')
                    continue
                out += [opening(targets), f'static_assert({trait});', '#else',
                        f'static_assert(!{trait});', '#endif']
                algorithm = program_type(data, entry['type'], backend)
                made += [f'#if ({condition(targets)}) && defined(WEBCPP_CRYPTO_HAS_'
                         f'{backend.upper()})',
                         f'    BOOST_TEST((webcpp::test::made<{algorithm}, '
                         f'families::{family["name"]}, {tag}, backends::{backend}>()));',
                         '#endif']
    # One check per cell, each a BOOST_TEST, which clang-tidy counts as a branch: main grows
    # with the table, so its complexity is the table's and not a function to split.
    out += ['// clang-format on', '',
            '// NOLINTNEXTLINE(readability-function-cognitive-complexity): one check per cell',
            'int main() {', '    // clang-format off']
    out += made
    out += ['    // clang-format on',
            '    return webcpp::test::exit_status(boost::report_errors());', '}', '']
    return '\n'.join(out)


def stale(files: Dict[Path, str]) -> List[Path]:
    """The files that differ from what generate.py writes, or that do not exist."""
    return sorted(path for path, text in files.items()
                  if not path.is_file() or path.read_text(encoding='utf-8') != text)


# A namespace table's column named by its names of code, then its plain name.
NAMED_COLUMN = re.compile(r'^((?:`[^`]+`(?:, )?)+): (.+)$')


def namespace_page(data: Data, namespace: str) -> str:
    """A namespace's comparison table: a column per name it holds, a row per question asked of
    each, the question in the row's first cell, so that the many questions stack down the page
    rather than across it."""
    entry = data['namespaces'][namespace]
    # A column named "`gcm`, `aes128_gcm`: AES-GCM" is headed by its plain name, AES-GCM, and
    # its names of code go to a row of their own: a phone's style labels each stacked cell with
    # its column's header as plain text, which would show the names of code as prose.
    headers: List[str] = []
    named: List[str] = []
    for row in entry['rows']:
        found = NAMED_COLUMN.match(row[0])
        headers.append(found.group(2) if found else row[0])
        named.append(found.group(1) if found else '')
    columns = [entry['columns'][0]] + headers
    rows = [[entry['columns'][index]] + [cite(data, row[index]) for row in entry['rows']]
            for index in range(1, len(entry['columns']))]
    if any(named):
        rows.insert(0, ['Names'] + named)
    widths = ','.join(['2h'] + ['5'] * len(entry['rows']))
    return table(columns, rows, f'cols="{widths}",')


def api_backends(data: Data, matrix: Matrix, operation: Data) -> str:
    """The backends that implement an operation, with their targets and Jamfile lines."""
    rows: List[List[str]] = []
    for backend in matrix.backends_of(operation['id']):
        facts = data['backends'][backend]
        rows.append([facts['title'], code(facts['jamfile']), names(facts['header']),
                     matrix.describe(operation['id'], backend)])
    text = (f'The backends of {names(operation["api"])}, from the test programs that run it:\n\n'
            + table(['Backend', 'Jamfile', 'Header', 'Targets'], rows, 'cols="1,2,2,4",'))
    if 'default' in operation:
        # The block cipher's default argument is AES-GCM's default: its table is AES-GCM's.
        family = family_of(data, operation.get('default_of', operation['family']))
        defaults = [[target_label(data, entry), default_title(data, entry)]
                    for entry in family['default']]
        text += (f'\n{marked(operation["default"])} The default per target, whatever the program '
                 'links, as <<crypto-backends-defaults>> gives it with its reasons and tests:\n\n'
                 + table(['Target', 'Default'], defaults, 'cols="1,1",'))
